def minimal_vectors(L, bound=3):
    vecs = [list(v) for v in product(*[range(-bound, bound + 1)] * L.n) if any(v)]
    mn = min(L.q(v) for v in vecs)
    return mn, [v for v in vecs if L.q(v) == mn]


def orthogonal_group(L, bound=3):
    """all isometries of a definite lattice L, via images of a basis of minimal vectors."""
    mn, mins = minimal_vectors(L, bound)
    # find r minimal vectors forming a Z-basis (det of Gram equals det L)
    basis = []
    for v in mins:
        trial = basis + [v]
        Gt = [[L.b(a, b) for b in trial] for a in trial]
        d = abs(det_frac(Gt))
        if d != 0:
            basis = trial
        if len(basis) == L.n:
            break
    assert len(basis) == L.n, "need a basis of minimal vectors"
    Gb = [[L.b(a, b) for b in basis] for a in basis]
    assert abs(det_frac(Gb)) == abs(L.det), (det_frac(Gb), L.det)
    Bcols = [[basis[j][i] for j in range(L.n)] for i in range(L.n)]  # matrix with basis as columns
    Binv = inv_frac(Bcols)
    out = []
    for images in permutations(mins, L.n):
        Gc = [[L.b(images[i], images[j]) for j in range(L.n)] for i in range(L.n)]
        if Gc != Gb:
            continue
        # matrix sending basis[i] -> images[i]: M = Images * Binv
        Img = [[images[j][i] for j in range(L.n)] for i in range(L.n)]
        M = mul(Img, Binv)
        if any(Fraction(x).denominator != 1 for row in M for x in row):
            continue
        M = [[int(x) for x in row] for row in M]
        if L.is_iso(M):
            out.append(M)
    return out


models = {
    "D4": [[2, -1, 0, 0], [-1, 2, -1, -1], [0, -1, 2, 0], [0, -1, 0, 2]],
    "A1^4": [[2, 0, 0, 0], [0, 2, 0, 0], [0, 0, 2, 0], [0, 0, 0, 2]],
    "A1^2": [[2, 0], [0, 2]],
}

for name, G in models.items():
    L = Lat(G, name)
    mn, mins = minimal_vectors(L, bound=2 if L.n <= 4 else 1)
    O_L = orthogonal_group(L, bound=2 if L.n <= 4 else 1)
    K = [M for M in O_L if L.trivial_on_A(M)]
    print(f"\n  {name}: rank {L.n}, det {L.det}, min norm {mn}, #minimal vectors {len(mins)}")
    print(f"    |O(L)| = {len(O_L)},  |K = ker(O(L)->O(A_L))| = {len(K)},"
          f"  |A_L| = {abs(L.det)}")
    # reflections in minimal vectors lying in O(L)
    refl = []
    for v in mins:
        M = reflection(L, v)
        if M is not None and L.is_iso(M):
            refl.append((tuple(v), M))
    reflK = [(v, M) for v, M in refl if L.trivial_on_A(M)]
    print(f"    reflections in minimal vectors: {len(refl)}; of these in K: {len(reflK)}")
    # subgroup generated by reflections inside K
    gens = [M for _, M in refl] + [M for v, M in reflK]
    seen = set()
    frontier = [tuple(tuple(r) for r in idm(L.n))]
    key = lambda M: tuple(tuple(r) for r in M)
    elems = {key(idm(L.n)): idm(L.n)}
    frontier = [idm(L.n)]
    while frontier:
        new = []
        for A in frontier:
            for M in gens:
                P = mul(M, A)
                k = key(P)
                if k not in elems:
                    elems[k] = P
                    new.append(P)
        frontier = new
    Wgen = set(elems.keys())
    Kset = set(key(M) for M in K)
    print(f"    subgroup generated by ALL reflections of L: order {len(Wgen)}; "
          f"|W(L) ∩ K| = {len(Wgen & Kset)}; |K| = {len(Kset)}")
    print(f"    is K generated by its own reflections? ", end="")
    gens2 = [M for v, M in reflK]
    elems2 = {key(idm(L.n)): idm(L.n)}
    frontier = [idm(L.n)]
    while frontier:
        new = []
        for A in frontier:
            for M in gens2:
                P = mul(M, A)
                k = key(P)
                if k not in elems2:
                    elems2[k] = P
                    new.append(P)
        frontier = new
    print(f"<reflections in K> has order {len(elems2)}, K has order {len(Kset)}, "
          f"equal = {set(elems2.keys()) == Kset}")
