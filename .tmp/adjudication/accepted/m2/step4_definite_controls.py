def qform(eps):
    """q on F2^4, type eps=+1 (Arf 0) or -1 (Arf 1)."""
    if eps > 0:
        return lambda x: (x[0] * x[1] + x[2] * x[3]) % 2
    return lambda x: (x[0] * x[1] + x[2] * x[2] + x[2] * x[3] + x[3] * x[3]) % 2


def count_O(q, n=4):
    cnt = 0
    mats = list(product(list(product([0, 1], repeat=n)), repeat=n))
    for rows in mats:
        M = [list(r) for r in rows]
        # invertibility over F2 via rank
        R = [r[:] for r in M]
        rk = 0
        for c in range(n):
            p = next((r for r in range(rk, n) if R[r][c]), None)
            if p is None:
                continue
            R[rk], R[p] = R[p], R[rk]
            for r in range(n):
                if r != rk and R[r][c]:
                    R[r] = [(R[r][j] ^ R[rk][j]) for j in range(n)]
            rk += 1
        if rk < n:
            continue
        if all(q([sum(M[i][j] * x[j] for j in range(n)) % 2 for i in range(n)]) == q(x)
               for x in product([0, 1], repeat=n)):
            cnt += 1
    return cnt


def order_O(m, eps=1):
    o = 2 * 2**(m * (m - 1)) * (2**m - eps)
    for i in range(1, m):
        o *= (2**(2 * i) - 1)
    return o


