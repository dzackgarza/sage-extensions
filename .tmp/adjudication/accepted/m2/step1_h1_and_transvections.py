def check_transvections(L, name, bound=2, cap=4000):
    n = L.n
    vecs = [list(v) for v in product(*[range(-bound, bound + 1)] * n)]
    vecs = [v for v in vecs if any(v)]
    iso = [v for v in vecs if L.q(v) == 0]
    bad_iso, bad_triv, nontriv = 0, 0, []
    count = 0
    import itertools
    for e in iso:
        for x in iso + [w for w in vecs if abs(L.q(w)) <= 4]:
            if L.b(e, x) != 0:
                continue
            Mt = transvection(L, e, x)
            count += 1
            if count > cap: break
            if Mt is None:
                bad_iso += 1
                continue
            if not L.is_iso(Mt):
                bad_iso += 1
            elif not L.trivial_on_A(Mt):
                nontriv.append((e, x))
    print(f"  {name}: tested {count} pairs (e isotropic, x in e-perp, |q(x)|<=4); "
          f"non-integral/non-isometric={bad_iso}; nontrivial on A={len(nontriv)}")
    if nontriv:
        print("    examples:", nontriv[:5])


