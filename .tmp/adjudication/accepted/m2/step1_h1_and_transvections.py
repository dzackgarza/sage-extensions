def block(*Gs):
    n = sum(len(G) for G in Gs)
    M = [[0] * n for _ in range(n)]
    o = 0
    for G in Gs:
        for i in range(len(G)):
            for j in range(len(G)):
                M[o + i][o + j] = G[i][j]
        o += len(G)
    return M


