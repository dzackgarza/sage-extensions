r"""The three checks on the cusp-4 vectors, and h against the lifts (#387)

AEGS Definition 2.6 (printed p. 586) gives `Gamma_{En,2}` as the image in
`O(T_En)` of `{g in O(L) : g o I_En = I_En o g, g(h) = h}`, and Definition 3.6
(printed p. 593) states that `W(Gamma_{En,2,e})` is generated by reflections in
the roots `alpha in T_En` with `alpha . e = 0`.  A `(-2)`-class `r` of
`v^perp/Zv` therefore lies in the reflection subgroup when it has a lift `rt`
with `rt^2 = -2`, `rt . v = 0` and `rt . h = 0`: the third is what a *class*
does not carry, since `s_rt(h) = h - 2 b(rt,h)/b(rt,rt) rt` is `h` exactly when
`h` is orthogonal to `rt`, and the lifts of a class are `rt + k v`, whose pairing
with `h` moves by `k b(v,h)`.

Nothing here uses a discriminant image.  Every number is `left^T G right` with
`G` the Gram matrix of the lattice in its own basis.
"""

