        def isotropic_elements_below_height(self, timelike, height):
            r"""Return the isotropic \(v\in L\) with \(\lvert b(v,t)\rvert\leq h\).

            The domain is :class:`HyperbolicLattices` — a lattice of signature
            \((n,1)\) or \((1,n)\) (V. V. Nikulin, *Reflection groups in
            hyperbolic spaces and the denominator formula for Lorentzian
            Kac--Moody Lie algebras*, Izvestiya: Mathematics 60 (1996), no. 2,
            arXiv:alg-geom/9503003v6, §1.1, (1.1.1), preprint p. 3) — and a lattice
            that was assembled by arithmetic is not in it until it is handed in:
            ``HyperbolicLattices(ZZ)(Lattices(ZZ)("U") + Lattices(ZZ)("A1"))``,
            because ``+`` returns a ``Lattices`` object.

            Put \(d=q(t)\) and \(a=b(v,t)\).  Then

            \[
              w=dv-at\in t^\perp, \qquad q(w)=-a^2d,
            \]

            and conversely \(v=(w+at)/d\) whenever that quotient is integral.
            Thus the height bound leaves only the finitely many integers
            \(-h\leq a\leq h\); for each one the possible \(w\)'s form one
            finite shell in the definite lattice \(t^\perp\).  The final
            divisibility check is exactly the condition that the rational
            reconstruction lies back in \(L\).
            """
            integers = _owned_integers()
            assert self.base_ring() is integers, (
                f"cannot enumerate isotropic vectors of {self} by height: the enumeration works only over ZZ, and {self} is over {self.base_ring()}"
            )
            if timelike.parent() is not self:
                timelike = self(timelike)
            height = integers(height)
            assert height >= integers.zero(), f"cannot enumerate isotropic vectors of {self} below height {height}: the height bound must be nonnegative"

            square = timelike.q()
            assert square != integers.zero(), f"{timelike} is not timelike in {self}: a timelike vector has nonzero square, and q({timelike}) = 0"
            complement = timelike.orthogonal_complement()
            assert complement.is_definite(), (
                f"{timelike} is not timelike in {self}: a vector is timelike exactly when its orthogonal complement is definite, and {complement} is not definite"
            )
            inclusion = complement.inclusion()
            # The framing coordinates arrive in the engine ring, so the divisibility test and
            # the reconstruction are engine arithmetic, and the candidate is read back as
            # integers: ``coordinate // square`` is a quotient of engine integers by the
            # engine image of ``square``, which is what makes the reconstruction integral.
            engine_square = _engine_element(integers, square)

            isotropic = []
            for height_value in range(-int(height), int(height) + 1):
                pairing = integers(height_value)
                target_square = -(pairing * pairing * square)
                match pairing == integers.zero():
                    case True:
                        shell = (complement.zero(),)
                    case False:
                        shell = complement.vectors_of_square(target_square)
                for perpendicular in shell:
                    numerator = inclusion(perpendicular) + pairing * timelike
                    coordinates = _framing_coordinates(numerator)
                    if not all(engine_square.divides(coordinate) for coordinate in coordinates):
                        continue
                    candidate = self(
                        tuple(int(coordinate // engine_square) for coordinate in coordinates)
                    )
                    if candidate.q() != integers.zero():
                        raise ArithmeticError(
                            f"the isotropic vectors of {self} at height {pairing} from "
                            f"{timelike} were computed wrongly: the candidate {candidate} "
                            f"has square {candidate.q()}, not 0"
                        )
                    if self.b(candidate, timelike) != pairing:
                        raise ArithmeticError(
                            f"the isotropic vectors of {self} at height {pairing} from "
                            f"{timelike} were computed wrongly: the candidate {candidate} "
                            f"has pairing {self.b(candidate, timelike)} with {timelike}, "
                            f"not {pairing}"
                        )
                    isotropic.append(candidate)
            return finite_ordered_set(tuple(isotropic))

        @cached_method
        def _edgewalk(self):
            r"""Walk the reflection chamber through the port's owned lattice API.

            The pinned port's entry point is
            ``sage_indefinite_port.indefinite.edgewalk.edgewalk_fundamental_domain``,
            whose signature is ``(lattice)`` alone at revision ``991b88b0`` and at
            the checkout the image carries: it prescribes no start vertex, no root
            filter and no termination switch, and it publishes no isometry route.
            So the walk is asked with the lattice and nothing else; the options an
            earlier revision of this wrapper advertised have no engine behind them
            and are not part of this API (#344).

            The port's entry uses signature ``(n,1)``. For ``(1,n)``, use the
            existing lattice twist functor and transport its report back to this
            literal lattice. If ``k`` is the coordinate-identical module
            identification from ``L(-1)`` to ``L``, then
            ``b_L(k(x), -k(r)) = b_{L(-1)}(x,r)``: vertex rays keep their
            coordinates and roots change sign.
            """
            from sage_indefinite_port.indefinite.edgewalk import (
                edgewalk_fundamental_domain,
            )
            from sage_extensions.categories.polyhedral_cones import (
                RationalPolyhedralCones,
            )

            if (self.signature_pair().second() == cardinal(1)) is True:
                return edgewalk_fundamental_domain(self)
            twist = Lattices(self.base_ring()).twist_functor(-1)
            working = HyperbolicLattices(self.base_ring())(twist(self))
            identification = self.module_category().Mor(working, self)(
                self.module_generator
            )
            report = edgewalk_fundamental_domain(working)
            cones = RationalPolyhedralCones(self)
            return AllcockEdgewalkReport(
                self,
                reflective=report.is_reflective(),
                simple_roots=tuple(
                    -identification(root) for root in report.simple_roots()
                ),
                vertices=tuple(
                    cones.from_rays(
                        tuple(identification(ray) for ray in vertex.primitive_rays()),
                        wall_roots=tuple(
                            -identification(root) for root in vertex.wall_roots()
                        ),
                    )
                    for vertex in report.vertices()
                ),
                isometry_generators=tuple(
                    twist(isometry)
                    for isometry in report.polyhedron_isometry_generators()
                ),
                reason_non_reflective=report.reason_non_reflective(),
            )

        def allcock_edgewalk(self):
            r"""Return Allcock's owned fundamental-domain report.

            The walk is the pinned port's own: one call with this lattice, at
            ``sage_indefinite_port.indefinite.edgewalk.edgewalk_fundamental_domain(lattice)``.
            It decides reflectivity, the simple roots of the chamber found, the
            vertex orbits, and the polyhedron's isometry generators; it takes no
            start vertex, no root filter and no termination switch, so this method
            has no parameters either (#344).
            """
            return self._edgewalk()

        def edgewalk_is_reflective(self) -> bool:
            r"""Return whether \(W(L)\) has finite index in \(O(L)\).

            A decision, unlike :meth:`is_reflective`: the edgewalk terminates
            on every input, reporting the fundamental polyhedron when there is
            one and the obstruction when there is not, so this answers ``True``
            or ``False`` and never a proposition.  The two methods answer the
            same mathematical question and are kept apart because they prove
            different things, not because they use different engines.
            """
            return self._edgewalk().is_reflective()

        def edgewalk_simple_roots(self):
            r"""Return the simple roots of the polyhedron the edgewalk walked.

            The outward normals of the walls of a fundamental polyhedron for
            \(W(L)\), the same wall set :meth:`vinberg_simple_roots` produces
            from a completed search.  A non-reflective lattice has no such
            polyhedron, and the set is then empty; ask
            :meth:`edgewalk_is_reflective` to tell that case from a lattice
            whose polyhedron has no walls.
            """
            return self._edgewalk().simple_roots()


