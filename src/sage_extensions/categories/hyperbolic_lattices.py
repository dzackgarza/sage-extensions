r"""Hyperbolic lattices and the reflection algorithms that run on them.

A lattice is hyperbolic in either Lorentzian sign convention, \((n,1)\) or
\((1,n)\), so that the real points \(L\otimes\mathbb R\) carry a light cone and
\(O(L)\) acts on the hyperbolic space of one of its two halves.  That is the
definition this owner works with: a free \(\mathbb Z\)-module of finite rank with
an integral symmetric bilinear form of signature \((n,1)\) (V. V. Nikulin,
*Reflection groups in hyperbolic spaces and the denominator formula for
Lorentzian Kac--Moody Lie algebras*, Izvestiya: Mathematics 60 (1996), no. 2,
doi:10.1070/IM1996v060n02ABEH000072, arXiv:alg-geom/9503003v6, §1.1, (1.1.1) and
the sentence after it, preprint p. 3: "Let \(S\colon M\times M\to\mathbb Z\)
(1.1.1) be a hyperbolic (i.e. of signature \((n,1)\)) integral symmetric bilinear
form over \(\mathbb Z\).  Here \(M\) is a free \(\mathbb Z\)-module of a finite
rank.  To be shorter, we call \(S\) as hyperbolic lattice").  The opposite sign
convention is the same lattice with its form twisted by \(-1\), which is why both
spellings are admitted here.  The mirror of a root \(r\) is the hyperplane
\(r^{\perp}\), and the reflection subgroup \(W(L)\leq O(L)\) is generated by the
reflections in the roots.

Vinberg's algorithm (Vinberg, *On groups of unit elements of certain quadratic
forms*, Mat. Sb. 87 (1972); *Hyperbolic reflection groups*, Russian Math.
Surveys 40 (1985)) enumerates the walls of a fundamental polyhedron for
\(W(L)\), starting from a chosen controlling vector.  It is a semi-decision
procedure: it halts with a certificate when the polyhedron closes, which is to
say when \(W(L)\) has finite covolume, and runs forever otherwise.  So
:meth:`is_reflective` here answers ``True`` or the proposition
``is_reflective(L)``, and never ``False``: a bounded search that did not close
proves nothing.

Both signs are admitted by this owner. The reflection algorithms use
\((n,1)\), with positive root squares. For the opposite sign, the form twist
by \(-1\) supplies that lattice. Vertex rays return with the same coordinates,
and roots return negated, preserving every half-space condition
\(b(x,r)\leq 0\).
"""

