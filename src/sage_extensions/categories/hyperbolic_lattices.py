        def fundamental_chamber(self, controlling_vector=None, *, max_roots=None, max_decompositions=None, admits_root=None):
            r"""Return the exact root-half-space cone cut out by Vinberg's walls.

            The chamber is ``{x : b(r,x) >= 0 for every accepted wall r}``.
            It retains those roots and their actual correlation covectors; the
            completion flag records whether the Vinberg search established the
            full wall set or only a bounded exploration prefix.

            ``admits_root`` restricts the algorithm to a reflection subgroup: a
            root is a wall only when ``admits_root(root)`` holds, which for a
            subgroup is the statement that the reflection in it lies there
            (:meth:`subgroup_fundamental_chamber` builds the callable for a
            subgroup given by generators, #297).  Without it the chamber is the
            full group's, and for a finite-index reflection subgroup that is a
            different polyhedron.
            """
            complete, roots = self._vinberg_search(
                controlling_vector, max_roots, max_decompositions, admits_root=admits_root
            )
            correlation = self.algebraic_correlation_morphism()
            return self.rational_polyhedral_cone(
                tuple(correlation(root) for root in roots),
                wall_roots=roots,
                complete=complete,
            )

        def subgroup_fundamental_chamber(self, controlling_vector=None, *, generators, max_roots=None, max_decompositions=None):
            r"""Return the chamber of the reflection subgroup generated by ``generators``.

            ``generators`` are isometries of this lattice; the reflection subgroup
            they generate is a subgroup of \(O(L)\), and its fundamental
            polyhedron is the intersection of the half-spaces of *its* roots, not
            of the lattice's.  Vinberg's algorithm is run with the root filter
            "the reflection in this root lies in the subgroup", which is applied
            inside the search and not to its output: a wall of the full group
            that the subgroup does not contain is not a wall of the subgroup's
            chamber, and filtering afterwards would return a smaller cone that is
            not a fundamental domain of anything.

            Membership of a reflection in the subgroup is the subgroup's own
            test (:meth:`sage_extensions.categories.group.groups.*.subgroup`), and
            an undecided membership propagates from it rather than being guessed:
            where the group machinery cannot decide membership of an integral
            reflection, this call does not return a chamber.

            Where it is needed (#285, research#654).  Sterk, *Compactifications
            of the period space of Enriques surfaces, Part I*, Math. Z. 207
            (1991), §4.3.1, p. 17 takes the chamber of \(G_v\), the image of the
            integral stabilizer \(\Gamma_v\) in \(O(v^\perp/\mathbf Z v)\); the
            five cusp diagrams of §4.3.5--4.3.9 have 12, 10, 12, 11 and 14 walls,
            while the full group's chamber of the cusp lattice \(U + E_8(-2)\)
            has ten, so four of the five are chambers of proper reflection
            subgroups and only this call produces them.  Vinberg's algorithm is
            E. B. Vinberg, *Some arithmetical discrete groups in Lobacevskii
            spaces* (1975), and Conway--Sloane, *SPLAG*, Ch. 27, §2.
            """
            subgroup = self.O().subgroup(tuple(generators))
            # The algorithm asks about the same root repeatedly, once per
            # decomposition it belongs to, and membership in a subgroup of
            # infinite index is not cheap; the answers are memoised for the one
            # call.  A caller whose subgroup has its own decidable criterion
            # should pass it to `fundamental_chamber(admits_root=...)` instead:
            # that is the path #285 takes, with the discriminant criterion of
            # the stabilizer's image (#312).
            decided = {}

            def admits_root(root):
                key = tuple(int(entry) for entry in root.to_vector())
                if key not in decided:
                    decided[key] = bool(self.reflection(root) in subgroup)
                return decided[key]

            return self.fundamental_chamber(
                controlling_vector,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
                admits_root=admits_root,
            )

        def subgroup_cusp_chamber(self, cusp, *, group_generators, max_roots=None, max_decompositions=None):
            r"""Return the chamber of the reflection part of ``Γ′`` anchored at the cusp ``cusp`` (#297).

            ``cusp`` is a primitive isotropic vector of this hyperbolic lattice,
            naming the \(0\)-cusp the chamber is anchored at, and ``group_generators``
            are isometries of this lattice generating the finite-index subgroup
            \(\Gamma' \le O(L)\).  The chamber returned is the fundamental
            polyhedron of the reflection part of \(\Gamma'\) — the subgroup
            generated by the reflections that lie in \(\Gamma'\) — with its
            walls as root vectors and their inner products, so that the Coxeter
            diagram of the polarized cusp is read off.

            **The algorithm is Vinberg's, with the membership decided in the
            finite discriminant quotient.**  Vinberg's algorithm
            (E. B. Vinberg, *On the groups of unit elements of certain quadratic
            forms*, Math. USSR Sb. 16 (1972), §3.2, pp. 27--29) enumerates the
            walls of the chamber of the group generated by the reflections the
            root filter admits: the construction after Proposition 3 (p. 27)
            takes the point \(p_0\) and the unique cell of \(\Gamma'\)
            coinciding with \(P_0\) near it, Proposition 4 (p. 28) states that
            the polyhedron cut out by the normals listed is that cell, and
            Proposition 5 (p. 29) states that the list breaks off once that
            polyhedron has finite volume.  A candidate root is a wall only when
            its reflection lies in \(\Gamma'\), and that question is decided
            where it is decidable: the discriminant images of the given
            group_generators generate a subgroup of the finite orthogonal group
            \(O(A_L)\), and membership in that subgroup is one sifting test of
            a Schreier--Sims stabilizer chain (A. Seress, *Permutation Group
            Algorithms*, Cambridge University Press 2003, chapter 4).  The sift
            decides \(\rho(s) \in \rho(\Gamma')\), which is the statement
            that \(s\) lies in the preimage \(\rho^{-1}(\rho(\Gamma'))\);
            where that preimage has no reflection beyond \(\Gamma'\)'s own —
            the reflection subgroups of the cusp lattices of the Enriques and
            Coble specimens — the two questions coincide, and the wall count
            read off the chamber is the published one.

            **The chamber does not depend on the point the walk measures from.**
            The controlling vector is a vertex of the chamber of the full
            reflection group \(W(L)\) of this lattice, selected among the
            vertices of positive square whose through-walls are a
            \(\mathbf Z\)-basis of the vertex's orthogonal complement by how
            many of its walls the subgroup filter admits: every vertex of that
            chamber lies in the chamber of every reflection subgroup of
            \(W(L)\) — a group generated by fewer reflections cuts out a bigger
            polyhedron — so the search anchored there computes the subgroup's
            own chamber by the three statements of Vinberg 1972 §3.2 quoted
            above, and no separate certificate is needed.

            Where it is needed (#297, research#668).  H. Sterk,
            *Compactifications of the period space of Enriques surfaces, Part I*,
            Math. Z. 207 (1991), §4.3.1, p. 17 publishes the Coxeter diagrams of
            the polarized cusps \(j = 2, \dots, 5\) with 10, 12, 11 and 14
            walls on the Enriques cusp lattice \(U(2) \oplus E_8(-2)\), and the
            Coble cusp lattice \(I_{1,8}(2) = \langle 2 \rangle \oplus
            E_8(-2)\) carries the diagrams of the \(527\) \(\Gamma_{Co}\)-
            orbits of primitive isotropic vectors of \(T_{Co}\).
            """
            ring = self.base_ring()
            vector = self(cusp)
            if self.q(vector) != ring.zero():
                raise ValueError(
                    f"cannot anchor the chamber of a subgroup at {cusp!r}: it has square "
                    f"{self.q(vector)}, not 0, so it names no 0-cusp of {self}"
                )
            if not vector.is_primitive():
                raise ValueError(
                    f"cannot anchor the chamber of a subgroup at {cusp!r}: the vector is not "
                    f"primitive, so it names no 0-cusp of {self}"
                )
            # The finite discriminant-image subgroup the given generators build.
            discriminant = self.discriminant_group()
            ambient = discriminant.orthogonal_group()
            rho = self.discriminant_representation()
            images = tuple(rho(generator) for generator in group_generators)
            subgroup = ambient.subgroup(
                tuple(image for image in images if image != ambient.one())
            )

            # One sift per distinct root: the algorithm asks about the same root
            # once per decomposition it belongs to, while the answer depends only
            # on the root's coordinates.
            decided = {}

            def admits_root(root):
                key = tuple(int(entry) for entry in root.to_vector())
                if key not in decided:
                    decided[key] = bool(rho(self.reflection(root)) in subgroup)
                return decided[key]

            # The anchor: the vertex of the full chamber admitting most walls.
            best = None
            for coordinates, square, through, basis in self._full_chamber_vertices():
                if square <= 0 or not basis:
                    # An ideal vertex is not a point of the hyperbolic space, and
                    # a vertex whose walls are not a Z-basis of its orthogonal
                    # complement leaves the walk's own cell condition unsatisfied.
                    continue
                admitted = sum(1 for root in through if admits_root(root))
                if best is None or admitted > best[0]:
                    best = (admitted, coordinates)
            if best is None:
                raise ValueError(
                    f"no vertex of the chamber of the full reflection group of {self} is a "
                    f"point of the hyperbolic space, so no controlling vector can be computed "
                    f"from the input"
                )
            control = self([int(entry) for entry in best[1]])

            return self.fundamental_chamber(
                control,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
                admits_root=admits_root,
            )

