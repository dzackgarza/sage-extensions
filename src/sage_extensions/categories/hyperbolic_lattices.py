def _signature_at_real_embedding(lattice, embedding):
    order = lattice.base_ring()
    field = order.fraction_field()
    rank = int(lattice.module_rank())
    rows = []
    for i in range(rank):
        row = []
        for j in range(rank):
            entry = field(lattice.gram_tensor()[i, j])
            image = embedding(entry)
            row.append(SageAA(_engine_element(embedding.codomain(), image)))
        rows.append(row)
    eigenvalues = engine_matrix(SageAA, rows).eigenvalues()
    positive = sum(value > 0 for value in eigenvalues)
    negative = sum(value < 0 for value in eigenvalues)
    radical = sum(value == 0 for value in eigenvalues)
    if radical:
        raise ValueError(
            f"{lattice} is degenerate at the real place {embedding}: the form has {radical} "
            f"zero eigenvalues there, and Vinberg's algorithm needs a nondegenerate form "
            f"at every real place"
        )
    return signature_pair(int(positive), int(negative))


class NumberFieldVinbergLattice(SageObject):
    r"""A lattice over ``O_K`` together with its distinguished hyperbolic real place.

    This is the arithmetic convention used by Bottinelli's
    ``VinbergsAlgorithmNF``: at the distinguished place the form has signature
    ``(n,1)``, while every other real conjugate is positive definite.  It is
    deliberately a different equipped object from :class:`HyperbolicLattices`,
    whose integral ``ZZ`` convention negates the form so roots have negative
    square.
    """

    def __init__(self, lattice, real_embedding) -> None:
        order = lattice.base_ring()
        field = order.fraction_field()
        real_algebraics = _owned_real_algebraic_numbers()
        assert int(field.degree()) == 2, (
            f"cannot run Vinberg's algorithm on {lattice} over {field}: the algorithm "
            f"holds over any totally real field, but the available implementation "
            f"(VinbergsAlgorithmNF) handles real quadratic fields only, and {field} has "
            f"degree {field.degree()}"
        )
        signature = field.signature()
        if int(signature.second()) != 0:
            raise ValueError(f"cannot run Vinberg's algorithm on {lattice}: its field of fractions {field} must be totally real, but it has signature {signature}")
        assert int(field.class_number()) == 1, (
            f"cannot run Vinberg's algorithm on {lattice} over {field}: the available "
            f"implementation (VinbergsAlgorithmNF) takes gcds of elements, which is "
            f"correct only when O_K is a principal ideal domain, and {field} has class "
            f"number {field.class_number()}"
        )
        if _engine_ring(order) != _engine_ring(field).ring_of_integers():
            raise ValueError(f"cannot run Vinberg's algorithm on {lattice}: it must be a lattice over the ring of integers of {field}, but its base ring is {order}")
        if real_embedding.domain() is not field or real_embedding.codomain() is not real_algebraics:
            raise ValueError(
                f"{real_embedding} cannot be the hyperbolic real place of {lattice}: it "
                f"must be an embedding {field} -> {real_algebraics}, but it is a map "
                f"{real_embedding.domain()} -> {real_embedding.codomain()}"
            )

        embeddings = field.embeddings(real_algebraics)
        if real_embedding not in embeddings:
            raise ValueError(f"{real_embedding} cannot be the hyperbolic real place of {lattice}: it is not one of the real embeddings {embeddings} of {field}")
        selected_position = embeddings.ranking_map()(real_embedding)
        selected_signature = _signature_at_real_embedding(lattice, real_embedding)
        rank = int(lattice.module_rank())
        if (
            (selected_signature.first() == cardinal(rank - 1)) is not True
            or (selected_signature.second() == cardinal(1)) is not True
        ):
            raise ValueError(f"{lattice} is not hyperbolic at the real place {real_embedding}: it must have signature ({rank - 1}, 1) there, but has {selected_signature}")
        other_signatures = finite_ordered_set(
            tuple(_signature_at_real_embedding(lattice, embeddings[position]) for position in embeddings.index_set() if position != selected_position)
        )
        if any(
            (other.first() == cardinal(rank)) is not True
            or (other.second() == cardinal(0)) is not True
            for other in other_signatures
        ):
            raise ValueError(
                f"cannot run Vinberg's algorithm on {lattice} with hyperbolic place "
                f"{real_embedding}: at every other real place the form must be positive "
                f"definite, of signature ({rank}, 0), but the signatures there are "
                f"{other_signatures}"
            )

        self._lattice = lattice
        self._real_embedding = real_embedding
        self._selected_signature = selected_signature
        self._other_signatures = other_signatures

    def lattice(self):
        return self._lattice

    def real_embedding(self):
        return self._real_embedding

    def signature_at_selected_place(self):
        return self._selected_signature

    def other_signatures(self):
        return self._other_signatures

    def _serialized_field(self):
        field = self.lattice().base_ring().fraction_field()
        engine = _engine_ring(field)
        degree = int(engine.degree())
        coefficients = tuple(engine.defining_polynomial().list())
        return tuple(_rational_pair(coefficients[index] if index < len(coefficients) else SageQQ.zero()) for index in range(degree + 1))

    def _serialized_gram(self):
        lattice = self.lattice()
        order = lattice.base_ring()
        field = order.fraction_field()
        field_engine = _engine_ring(field)
        order_engine = _engine_ring(order)
        rank = int(lattice.module_rank())
        return tuple(
            tuple(
                _number_field_coefficients(
                    field_engine,
                    field_engine(order_engine(_engine_element(order, lattice.gram_tensor()[i, j]))),
                )
                for j in range(rank)
            )
            for i in range(rank)
        )

    def _selected_primitive_approximation(self):
        field = self.lattice().base_ring().fraction_field()
        image = self.real_embedding()(field.primitive_element())
        backend = _engine_element(_owned_real_algebraic_numbers(), image)
        return str(backend.n(128))

    def _cross_root(self, serialized_row):
        lattice = self.lattice()
        order = lattice.base_ring()
        field = order.fraction_field()
        field_engine = _engine_ring(field)
        order_engine = _engine_ring(order)
        generator = field_engine.gen()
        coefficients = []
        for serialized_entry in serialized_row:
            value = field_engine.zero()
            for exponent, pair in enumerate(serialized_entry):
                numerator, denominator = pair
                value += SageQQ(numerator) / SageQQ(denominator) * generator**exponent
            integral = order_engine(value)
            coefficients.append(_owned_engine_element(order, integral))
        root = lattice(tuple(coefficients))
        if root.q() <= 0:
            raise ArithmeticError(f"VinbergsAlgorithmNF returned {root} as a root of {lattice}, but a root must have positive square and q({root}) = {root.q()}")
        return root

    def vinberg_simple_roots(self, *, count):
        r"""Return ``(complete, roots)`` from the pinned number-field Vinberg engine."""
        if int(count) <= 0:
            raise ValueError(f"cannot ask Vinberg's algorithm on {self.lattice()} for {count} simple roots: the number of roots must be positive")
        complete, rows = _vinberg_nf_roots(
            self._serialized_field(),
            self._serialized_gram(),
            self._selected_primitive_approximation(),
            int(count),
        )
        roots = finite_ordered_set(tuple(self._cross_root(row) for row in rows))
        return complete, roots

    def __repr__(self) -> str:
        return f"Number-field Vinberg lattice ({self.lattice()}, {self.real_embedding()})"


#: Sentinel for "the cell at the controlling vector has not been asked for yet".
_NO_CELL = object()


def _square_root_bound(value):
    r"""Return a rational bound of \(\sqrt{\text{value}}\), or ``None`` below zero.

    ``value`` is a non-negative :class:`fractions.Fraction`; since
    \(\sqrt{p/q}=\sqrt{pq}/q\), an integer square root of the product gives the
    bound exactly at the denominator's scale, and the caller's floor of it is
    the floor of the real root.
    """
    if value < 0:
        return None
    return Fraction(isqrt(value.numerator * value.denominator), value.denominator)


def _ldl_factorisation(gram):
    r"""Return \((D,L)\) with \(L\) unit lower triangular and \(L^tDL=\) ``gram``.

    Exact rational \(LDL^t\) of a symmetric matrix, or ``None`` when a pivot is not
    positive.  The Gram of the normals of a cell is positive definite, so a
    ``None`` here means the normals are not the normals of a cell, and the caller
    enumerates the whole layer instead of trusting a factor that does not exist.
    """
    size = int(gram.nrows())
    rational = gram.change_ring(SageQQ)
    diagonal = [Fraction(0)] * size
    triangular = [[Fraction(0)] * size for _ in range(size)]
    for index in range(size):
        pivot = Fraction(int(rational[index, index])) - sum(
            (triangular[index][k] ** 2 * diagonal[k] for k in range(index)), Fraction(0)
        )
        if pivot <= 0:
            return None
        diagonal[index] = pivot
        triangular[index][index] = Fraction(1)
        for row in range(index + 1, size):
            numerator = Fraction(int(rational[row, index])) - sum(
                (triangular[row][k] * triangular[index][k] * diagonal[k] for k in range(index)),
                Fraction(0),
            )
            triangular[row][index] = numerator / pivot
    return diagonal, triangular


def _exact_square_root(value):
    r"""Return the rational root of ``value`` when it is a square, and ``None`` otherwise."""
    if value < 0:
        return None
    root = _square_root_bound(value)
    return root if root * root == value else None


def _vinal_parallelepiped_points(inserted):
    r"""Return the integer points of the half-open parallelepiped of the rows.

    ``inserted`` is a nonsingular integer matrix -- in the engine's constructor
    it is a basis of the controlling vector's orthogonal complement with the
    controlling vector inserted as the last row.  The integer points of
    ``{t * inserted : 0 <= t_i < 1}`` are one representative of each coset of
    the row lattice in ``ZZ^n``; they are the engine's ``W``, the offsets the
    layer enumeration adds to the multiples of the controlling vector, and
    ``VinAl`` checks them against the controlling vector on construction.

    vinal's ``GetIntegerPoints`` (Bogachev and Perepechko's ``vinal``,
    ``src/sage/vinal.py``) finds them by enumerating the coordinate box between
    the negative and the positive row sums and testing each point against the
    parallelepiped; that box has the product of those sums as its size, which
    at the fourth Enriques cusp is about `1.3 \cdot 10^{14}` points for a
    two-element ``W``, and the engine's constructor does not return.  The same
    set is found without enumeration: the Smith normal form
    ``D = U * inserted * V`` (Sage's ``smith_form``, with ``U`` and ``V``
    unimodular) writes the row lattice as ``{s * D * V^{-1} : s in ZZ^n}``, so
    ``x = a * V^{-1}`` with ``a`` in the box ``prod_i [0, D_i)`` runs once
    through every coset, and the representative of ``x``'s coset inside the
    half-open parallelepiped is
    ``x - floor(x * inserted^{-1}) * inserted``: subtracting the floor of the
    row-basis coordinates moves the point by a row-lattice element and leaves
    every row-basis coordinate in ``[0, 1)``.  Each point returned is integral
    because both ``x`` and the subtracted row combination are, and the set is
    exactly the one the bounding-box enumeration would return, so the engine's
    behaviour changes only in the time the constructor takes.
    """
    size = inserted.nrows()
    diagonal, _left, right = inserted.smith_form()
    inverse = right.inverse()
    reduction = inserted.inverse()
    points = []
    for coefficients in _cartesian_product(
        *[range(abs(int(diagonal[index, index]))) for index in range(size)]
    ):
        representative = engine_vector(SageQQ, coefficients) * inverse
        coordinates = representative * reduction
        shifted = representative - engine_vector(
            SageQQ, [entry.floor() for entry in coordinates]
        ) * inserted
        points.append(tuple(int(entry) for entry in shifted))
    return points


def _filtered_vinal_class():
    r"""Return the engine's ``VinAl`` subclass that walks one reflection subgroup.

    The class carries the library's repairs of the engine's walk: the
    polynomial-time coset representatives of the constructor, the candidate
    tests of #312, and the layer enumeration in the coordinates of the cell at
    the controlling vector (#285, #400).  It is built by a factory and not at
    the module's top level because ``vinal`` is imported here, so that
    importing this module does not pay for the engine's own imports; and it is
    a factory rather than a class defined inside :func:`_vinal_vinberg_roots`
    so that a probe can hold the walk object itself and read its restricted
    layer enumeration against the engine's whole-lattice one, layer by layer
    (#400).
    """
    from vinal import NegativeVector, VinAl

    class _FilteredVinAl(VinAl):
        r"""Vinberg's algorithm over one lattice, restricted to a reflection subgroup.

        ``VinAl`` enumerates the roots of the whole lattice and accepts a
        candidate when it is a root and lies beyond the walls already found
        (its ``IsRoot`` and ``IsNewRoot``).  A reflection subgroup of
        finite index has a different polyhedron -- the intersection of the
        half-spaces of its own root system -- so a candidate must also have
        its reflection in the subgroup.  This class adds exactly that test,
        by ``IsRoot``, which both the initial cusp cone and the candidate
        enumeration go through.

        The candidate enumeration asks the test in
        :meth:`IsNewRoot` *last*.  ``VinAl.IsNewRoot`` is the conjunction
        "not a repeat, a root, beyond every accepted wall", and the
        subgroup test belongs to that conjunction; its position among the
        conjuncts is free, and it is the only conjunct whose cost is a sift
        through a stabilizer chain rather than a handful of rank-ten
        integer inner products.  Asked first, it answers for every root of
        the lattice the enumeration reaches, most of which point away from
        the chamber being built and are rejected by the wall condition
        whatever the subgroup says; asked last, it answers only for the
        candidates inside that chamber.  The accepted set is the same
        either way, because the conjunction is.
        """

        def __init__(
            self, M, v0=None, use_coxiter=False, output=None, *, admits_root
        ) -> None:
            r"""Mirror ``VinAl.__init__`` with the library's own ``W``.

            The engine's constructor finds the coset representatives of the
            row lattice of the inserted matrix by enumerating a coordinate
            bounding box, which at the fourth Enriques cusp has about
            `1.3 \cdot 10^{14}` points for a two-element ``W`` and does not
            return; :func:`_vinal_parallelepiped_points` returns the same
            points in polynomial time, and the rest of the construction is
            ``VinAl``'s own, attribute for attribute.  The controlling
            vector may be omitted, in which case the engine's own
            ``NegativeVector`` picks one.
            """
            self._admits_root = admits_root
            self._cell = _NO_CELL
            self.output = output
            self.use_coxiter = use_coxiter
            self.M = M
            self.n = M.ncols()
            self.V = SageFreeModule(SageZZ, self.n, inner_product_matrix=M)
            self.v0 = NegativeVector(self.V) if v0 is None else self.V(v0)
            kernel_matrix = engine_matrix(
                [self.v0.dot_product(column) for column in M.columns()]
            )
            self.V1 = self.V.submodule(kernel_matrix.right_kernel())
            self.M1 = self.V1.gram_matrix()
            inserted = self.V1.matrix().insert_row(self.n - 1, self.v0)
            self.W = [self.V(w) for w in _vinal_parallelepiped_points(inserted)]
            self.W.sort(key=lambda entry: -self.v0.inner_product(entry))
            self.En = abs(self.M.det() / GCD_list(self.M.adjugate().list()))
            self.root_lengths = [
                k
                for k in range(1, 2 * int(self.En) + 1)
                if ((2 * int(self.En)) % k == 0)
            ]
            self.roots = []
            self.check_validity()

        def _in_the_subgroup(self, vector) -> bool:
            return bool(
                self._admits_root(tuple(int(entry) for entry in vector))
            )

        def IsRoot(self, vector):
            r"""Vinberg's root test with the subgroup test, for the initial cone.

            The initial cone is cut by the roots orthogonal to the
            controlling vector, and those are candidates with no wall
            condition to satisfy first: every one of them is asked.
            """
            return super().IsRoot(vector) and self._in_the_subgroup(vector)

        def IsNewRoot(self, vector):
            r"""``VinAl.IsNewRoot`` with the subgroup test asked after the wall condition.

            Two of the conjuncts are answered here by their exact
            equivalents rather than the engine's spells, because the
            engine's spells cost a Sage matrix routine per candidate and
            the candidates number in the millions (measured at Sterk's
            first cusp: 1,855,003 candidates, of which the engine's root
            test took 337.8 s and its dependence check 92.9 s, against
            72.4 s for the whole layer enumeration):

            - the repeat check asks whether the candidate is at distance
              zero from the controlling vector, that is one inner product
              \(b(\text{candidate}, v_0)=0\).  ``VinAl`` instead asks
              whether the candidate lies in the span of the first
              \(n-1\) accepted roots, which is the same question when
              those roots span \(v_0^\perp\) and is not when they do not:
              at the fourth Enriques cusp the distance-zero admitted roots
              span rank eight of the rank nine, the engine's span is a
              foreign rank-nine subspace, and the walls it wrongly refuses
              are the ones the chamber needs to close.  Every root at
              distance zero was already decided by ``FundCone``, whose
              walls are exactly the cell at \(v_0\): a chamber coincides
              with that cell near \(v_0\) (Vinberg 1972, §3.2, the
              construction after Proposition 3, p. 27), so no further
              distance-zero mirror bounds it, and each such candidate is
              refused whatever the span is;
            - the root test asks whether the candidate's reflection
              preserves the lattice, i.e. whether its square divides twice
              each of its pairings with the framing generators; the
              pairings are one contraction of the candidate against the
              engine's Gram matrix, and the divisibility is ten modular
              checks on the result.

            Both equivalents answer the same question the engine's spell
            answers; the accepted set is the same, and only the cost of
            asking changes.
            """
            if vector.inner_product(self.v0) == 0:
                return False
            pairings = vector * self.M
            square = vector.inner_product(vector)
            if any((2 * pairing) % square != 0 for pairing in pairings):
                return False
            if not all(vector.inner_product(root) <= 0 for root in self.roots):
                return False
            return self._in_the_subgroup(vector)

        def NextRoot(self, max_decompositions=None, progress=None):
            r"""Yield the engine's new roots, re-checked against the accepted ones.

            ``VinAl.NextRoot`` filters a whole layer against the roots
            accepted when the layer starts and then yields every survivor,
            so two candidates of one layer that pair positively both become
            walls, and a candidate the layer solver lists twice is appended
            twice -- at the fourth Enriques cusp the same wall appeared
            twice in the accepted list.  Vinberg's sequence (38) asks the
            wall condition of every root as it is written down (1972,
            §4.1, p. 30), so each root is yielded only after it still
            pairs nonpositively with everything accepted so far and is not
            already among them.
            """
            for root in super().NextRoot(max_decompositions, progress):
                if root in self.roots:
                    continue
                if any(root.inner_product(other) > 0 for other in self.roots):
                    continue
                yield root

        def cell(self):
            r"""Return the cell at the controlling vector, or ``None`` when it does not span.

            Vinberg 1972, §3.2, rule 1 and (39) (p. 27): before the sequence
            (38) starts, the normals are the roots whose mirrors pass through
            the point \(p_0\), and they cut the cell \(P_0\) at it.  Those are
            the roots orthogonal to ``v0``, which is what ``FundCone``
            returns and what ``roots`` holds when the candidate enumeration
            begins.

            For the layer enumeration of §4.1 (p. 30) the normals of \(P_0\)
            are useful only when they span \(v_0^\perp\) up to one
            lineality direction integrally, so the cell is returned with its
            Gram matrix and a factor \(R\) with \(R^tR=G\), and ``None``
            when the count of normals is neither the rank nor one less than
            it, when the Gram has a positive entry off the diagonal (a cell
            of an acute-angled polyhedron has \(g_{ij}\le0\)), or when the
            normals do not span \(v_0^\perp\) integrally in that form.  The
            Gram of such a cell is a Stieltjes matrix, so its inverse has
            no negative entry, and that is what makes the cone of (58) sit
            inside the orthant of the coefficients: see
            :meth:`Roots_decomposed_into`.

            A cell of \(\operatorname{rank}(v_0^\perp)-1\) normals -- a cusp
            cell, whose cone has one lineality direction (#387,
            ``results/issue387-the-group-of-the-card-chamber.md`` §4) -- is
            returned with that direction: the cell's fourth entry is the
            primitive vector \(m\) of \(v_0^\perp\) orthogonal to every
            normal, its square, the inverse of the frame
            \((w_1,\dots,w_r,m,v_0)\), and the representatives of the cosets
            of the lattice \(\langle w_1,\dots,w_r,m\rangle\) in
            \(v_0^\perp\).  At the fourth Enriques cusp that lattice has
            index two, so half of \(v_0^\perp\) lies outside the coordinates
            of the normals and \(m\) alone, and a vector of \(v_0^\perp\)
            is written in those coordinates only after its coset
            representative is added; the basis case is the same structure
            with the single trivial coset.
            """
            if self._cell is not _NO_CELL:
                return self._cell
            roots = getattr(self, "roots", None)
            if not roots:
                # ``FundCone`` is cutting the cell itself and asks the layer
                # enumeration on the way; there is nothing to cache yet.
                return None
            self._cell = None
            normals = tuple(root for root in roots if self.v0.inner_product(root) == 0)
            rank = int(self.n) - 1
            if len(normals) not in (rank, rank - 1):
                return None
            gram = engine_matrix([[int(u.inner_product(v)) for v in normals] for u in normals])
            if any(
                gram[i, j] > 0
                for i in range(len(normals))
                for j in range(len(normals))
                if i != j
            ):
                return None
            factor = _ldl_factorisation(gram)
            if factor is None:
                return None
            if len(normals) == rank:
                if int(abs(gram.det())) != int(abs(self.M1.det())):
                    return None
                self._cell = (normals, gram.change_ring(SageQQ), factor, None)
                return self._cell
            # One lineality direction: the primitive vector of v0^perp
            # orthogonal to every normal.  The normals are independent,
            # because their Gram factored, so together with v0 they have
            # rank n-1 and the kernel below is a line; its primitive
            # generator is integral, orthogonal to the normals and to v0,
            # and of positive square, because it lies in the positive
            # definite v0^perp.
            rows = engine_matrix([list(normal) for normal in normals] + [list(self.v0)])
            generator = (rows * self.M).right_kernel().basis()[0]
            entries = [int(entry) for entry in generator]
            leading = next(entry for entry in entries if entry)
            if leading < 0:
                entries = [-entry for entry in entries]
            m = self.V(entries)
            m_square = int(m.inner_product(m))
            # The frame of the normals and m generates v0^perp up to a
            # finite index, and the index is paid in coset
            # representatives: a vector of v0^perp is written in the
            # frame's coordinates only after its representative is added.
            # The representatives are the integer points of the
            # parallelepiped of the frame's coordinates in a basis of
            # v0^perp, the same construction as the engine's own W.
            basis = self.V1.matrix()
            inserted = basis.insert_row(int(self.n) - 1, self.v0)
            coordinates = (
                engine_matrix([list(normal) for normal in normals] + [entries])
                * inserted.change_ring(SageQQ).inverse()
            ).matrix_from_columns(range(len(normals) + 1))
            if any(value not in SageZZ for value in coordinates.list()):
                # The frame lies in v0^perp, so its coordinates in a basis of
                # v0^perp are integral; a fractional entry means the frame is
                # not what the construction above says it is.
                return None
            cosets = tuple(
                self.V(list(engine_vector(SageZZ, point) * basis))
                for point in _vinal_parallelepiped_points(coordinates.change_ring(SageZZ))
            )
            frame = engine_matrix([list(normal) for normal in normals] + [entries, list(self.v0)])
            self._cell = (
                normals,
                gram.change_ring(SageQQ),
                factor,
                (m, m_square, frame.change_ring(SageQQ).inverse(), cosets),
            )
            return self._cell

        def Roots_decomposed_into(self, a, k):
            r"""Return the candidates of one layer whose normal coordinates are nonpositive.

            Vinberg, *On the groups of unit elements of certain quadratic
            forms*, Math. USSR Sb. 16 (1972), §4.1, p. 30: "Construction of
            the sequence (38) thus reduces to writing down those solutions of
            the Diophantine equation (57) that satisfy conditions (58) in
            increasing order of the quantity (59), and in checking conditions
            (49) for each solution as it is written down."  Conditions (58)
            are the inequalities \(b_0\le0,\dots,b_n\le0\) against the normals
            already accepted — the cone conditions — and (49) is the height
            comparison, which :meth:`IsNewRoot` makes of every solution.

            This method writes down the solutions of the layer's equation
            (57) whose coordinates along the cell normals are nonpositive,
            and never a solution outside that orthant.  The candidate is
            \(v=a+v_1\) with \(v_1\) in \(v_0^\perp\), the normals of the
            cell at the controlling vector are \(w_1,\dots,w_r\), and
            \(u\), the coordinates of \(v\) along the normals, pair as
            \(b(v,w_i)=\sum_jg_{ij}u_j\), so (58) says \(Gu\le0\).  The
            Gram of a cell is a Stieltjes matrix, so \(G^{-1}\) has no
            negative entry and \(u=G^{-1}(Gu)\) is non-positive whenever
            \(Gu\) is: every solution of (58) has nonpositive normal
            coordinates, the orthant is a superset of the cone, and the
            walls, which :meth:`IsNewRoot` takes out of it, are never
            skipped.  Writing \(a'\) for the offset \(a\) with its normal
            coordinates cancelled and \(d=-u\), the norm equation (57)
            becomes \(d^tGd=k-q(a')\) with \(d\ge0\) in the orthant and
            \(d\) in the coset of the offset's own coordinates: that is
            enumerated by completion of squares along the factor \(R\),
            every coefficient respecting the same lower bound, so nothing
            outside the orthant is written down.

            A cell with one lineality direction (#400) enumerates the layer
            in the same coordinates with the lineality coordinate added.
            Every vector of \(v_0^\perp\) is, for exactly one coset
            representative \(s\) of \(\langle w_1,\dots,w_r,m\rangle\) in
            \(v_0^\perp\), the vector \(s-\sum d_iw_i+tm\) with
            \(d\in\mathbf Z^r\) and \(t\in\mathbf Z\); the frame
            \((w_1,\dots,w_r,m,v_0)\) has block-diagonal Gram, because
            \(m\) is orthogonal to the normals and to \(v_0\), so with
            \(a+s=\sum x_iw_i+\alpha m+\gamma v_0\) the norm equation (57)
            reads \(d^tGd+q(m)(\alpha+t)^2=k-\gamma^2q(v_0)\): the integer
            \(t\) is bounded on both sides by that equation,
            \(q(m)(\alpha+t)^2\le k-\gamma^2q(v_0)\), and each bounded
            \(t\) leaves the same positive-definite equation in
            \(d\ge0\).

            Layers whose cell is not available — the initial cone's own
            enumeration, and a controlling vector whose cell spans
            \(v_0^\perp\) integrally in neither form — keep ``VinAl``'s
            enumeration of the whole layer.
            """
            cell = self.cell()
            if cell is None:
                return super().Roots_decomposed_into(a, k)
            normals, gram, factor, lineality = cell
            if lineality is None:
                squares, triangular = factor
                beta = [Fraction(int(a.inner_product(normal))) for normal in normals]
                center = [
                    Fraction(int(value.numerator()), int(value.denominator()))
                    for value in gram.solve_right(engine_vector(SageQQ, beta))
                ]
                offsets = [
                    sum((triangular[j][i] * center[j] for j in range(len(normals))), Fraction(0))
                    for i in range(len(normals))
                ]
                remaining = Fraction(int(k) - int(a.inner_product(a))) + sum(
                    (beta[i] * center[i] for i in range(len(normals))), Fraction(0)
                )
                if remaining < 0:
                    return []
                candidates = self._cone_combinations(normals, factor, offsets, remaining, center)
                found = [a + vector for vector in candidates]
                for candidate in found:
                    if int(candidate.inner_product(candidate)) != int(k):
                        raise ArithmeticError(
                            f"the cone enumeration of the layer at {a} returned {candidate}, whose square is "
                            f"{candidate.inner_product(candidate)}, not the layer's {k}"
                        )
                return found
            m, m_square, frame_inverse, cosets = lineality
            v0_square = Fraction(int(self.v0.inner_product(self.v0)))
            m_square_fraction = Fraction(m_square)
            found = []
            for coset in cosets:
                offset = a + coset
                coordinates = (
                    engine_vector(SageQQ, [int(entry) for entry in offset]) * frame_inverse
                )
                x = [
                    Fraction(int(value.numerator()), int(value.denominator()))
                    for value in coordinates[: len(normals)]
                ]
                alpha = Fraction(
                    int(coordinates[len(normals)].numerator()),
                    int(coordinates[len(normals)].denominator()),
                )
                gamma = Fraction(
                    int(coordinates[len(normals) + 1].numerator()),
                    int(coordinates[len(normals) + 1].denominator()),
                )
                remaining = Fraction(int(k)) - gamma * gamma * v0_square
                if remaining < 0:
                    continue
                triangular = factor[1]
                offsets = [
                    sum((triangular[j][i] * x[j] for j in range(len(normals))), Fraction(0))
                    for i in range(len(normals))
                ]
                # The integers t with q(m)(alpha + t)^2 <= remaining: the
                # square-root bound is a floor of the real root, so each
                # end is extended while the exact inequality still holds.
                bound = _square_root_bound(remaining / m_square_fraction)
                high = int((bound - alpha).__floor__())
                while m_square_fraction * (alpha + high + 1) ** 2 <= remaining:
                    high += 1
                low = int((-bound - alpha).__ceil__())
                while m_square_fraction * (alpha + low - 1) ** 2 <= remaining:
                    low -= 1
                for t in range(low, high + 1):
                    square = remaining - m_square_fraction * (alpha + t) ** 2
                    for combination in self._cone_combinations(
                        normals, factor, offsets, square, x
                    ):
                        found.append(offset + combination + t * m)
            for candidate in found:
                if int(candidate.inner_product(candidate)) != int(k):
                    raise ArithmeticError(
                        f"the cone enumeration of the layer at {a} returned {candidate}, whose square is "
                        f"{candidate.inner_product(candidate)}, not the layer's {k}"
                    )
            return found

        @staticmethod
        def _cone_combinations(normals, factor, offsets, square, floors=None):
            r"""Return \(-d_1w_1-\dots-d_nw_n\) for \(d\ge\text{floors}\) integral with \(d^tGd=\) ``square``.

            ``factor`` is the pair \((D,L)\) of :func:`_ldl_factorisation`, so
            \(d^tGd=\sum_iD_i(L^td)_i^2\) and the \(i\)-th entry
            \((L^td)_i=d_i+\sum_{j>i}L_{ji}d_j\) depends on \(d_i,\dots,d_n\)
            only.  Descending from \(d_n\), the value
            \(s-\sum_{j>i}D_j(L^td)_j^2\) bounds \(d_i\) from both sides, and the
            last coefficient is pinned to an exact square.

            The coefficients are those of the candidate written in the
            cell's frame, so the orthant \(u\le0\) of conditions (58)
            (\(u\) the candidate's normal coordinates) is a lower bound on
            them: ``floors`` is that bound, the normal coordinates of the
            layer's offset, and it is zero only when the offset has no
            component along the normals — the whole-lattice offset of the
            fourth Enriques cusp has negative ones.  Each level's range is
            the integers that satisfy both the bound and the exact residual
            inequality \(D_i(L^td)_i^2\le s\): the square-root bound is a
            floor, so each end of the range is extended while the exact
            inequality still holds.
            """
            size = len(normals)
            squares, triangular = factor
            bounds = (
                [Fraction(0)] * size
                if floors is None
                else [Fraction(value) for value in floors]
            )
            coefficients = [0] * size
            found = []

            def descend(level, remaining):
                shift = sum(
                    (triangular[j][level] * coefficients[j] for j in range(level + 1, size)),
                    Fraction(0),
                ) - offsets[level]
                if level == 0:
                    root = _exact_square_root(remaining / squares[0])
                    if root is None:
                        return
                    for sign in ((1,) if root == 0 else (1, -1)):
                        value = sign * root - shift
                        if value.denominator != 1 or value < bounds[0]:
                            continue
                        coefficients[0] = int(value)
                        combination = [0] * int(normals[0].degree())
                        for position, coefficient in enumerate(coefficients):
                            if coefficient:
                                combination = [
                                    entry - coefficient * int(other)
                                    for entry, other in zip(combination, normals[position])
                                ]
                        found.append(normals[0].parent()(combination))
                    coefficients[0] = 0
                    return
                bound = _square_root_bound(remaining / squares[level])
                if bound is None:
                    return
                high = int((bound - shift).__floor__())
                while squares[level] * (high + 1 + shift) ** 2 <= remaining:
                    high += 1
                low = int((-bound - shift).__ceil__())
                while squares[level] * (low - 1 + shift) ** 2 <= remaining:
                    low -= 1
                for value in range(max(bounds[level].__ceil__(), low), high + 1):
                    coefficients[level] = value
                    entry = value + shift
                    descend(level - 1, remaining - squares[level] * entry * entry)
                coefficients[level] = 0

            descend(size - 1, Fraction(square))
            return found

    return _FilteredVinAl


def _vinal_vinberg_roots(gram, controlling_vector, max_roots, max_decompositions, admits_root=None):
    r"""Run Vinberg's algorithm on a Gram matrix of signature \((n,1)\).

    Returns the completeness flag of the search and the coordinate rows of the
    accepted roots.  ``vinal`` is Bogachev and Perepechko's implementation of
    the algorithm; ``FindRoots`` reports whether the fundamental polyhedron was
    established, which is the algorithm's own termination criterion.

    ``admits_root`` restricts the algorithm to a reflection subgroup: a candidate
    root is accepted only when its coordinate row is admitted, and the same test
    filters the roots of the initial cone at the controlling vector.  A finite
    index reflection subgroup of \(O(L)\) has its own polyhedron and not the
    full group's, so the restriction is part of the algorithm and not a filter
    of its output (#297).
    """
    if admits_root is None:
        from vinal import VinAl

        algorithm = VinAl(gram, controlling_vector, False, None)
    else:
        algorithm = _filtered_vinal_class()(
            gram, controlling_vector, False, None, admits_root=admits_root
        )
    complete = algorithm.FindRoots(max_roots=max_roots, max_decompositions=max_decompositions)
    return bool(complete), tuple(tuple(root) for root in algorithm.roots)


class AllcockEdgewalkReport(SageObject):
    r"""Owned fundamental-domain data returned by Allcock's edgewalk.

    Each vertex orbit representative of the fundamental polyhedron is the
    ray of ``L tensor QQ`` it spans, a rational polyhedral cone whose wall
    roots are the roots of the walls through the vertex.  The vertex is
    ideal exactly when that ray is isotropic.
    """

    def __init__(
        self,
        lattice,
        *,
        reflective,
        simple_roots,
        vertices,
        isometry_generators,
        reason_non_reflective=None,
    ) -> None:
        self._lattice = lattice
        self._reflective = bool(reflective)
        self._simple_roots = finite_ordered_set(tuple(simple_roots))
        self._vertices = finite_ordered_set(tuple(vertices))
        self._isometry_generators = finite_ordered_set(tuple(isometry_generators))
        self._reason_non_reflective = reason_non_reflective

    def lattice(self):
        return self._lattice

    def is_reflective(self) -> bool:
        return self._reflective

    def reason_non_reflective(self):
        r"""The source's reason when the walk stopped by proving non-reflectivity, else ``None``."""
        return self._reason_non_reflective

    def simple_roots(self):
        return self._simple_roots

    def vertices(self):
        return self._vertices

    def polyhedron_isometry_generators(self):
        return self._isometry_generators

    @cached_method
    def polyhedron_isometry_group(self):
        return self.lattice().O().subgroup(self.polyhedron_isometry_generators())

    def __repr__(self) -> str:
        return f"Allcock edgewalk report for {self.lattice()}"


class HyperbolicLattices(OwnedCategoryOverBaseRing):
    r"""Lattices with either Lorentzian sign convention, ``(n,1)`` or ``(1,n)``.

    A hyperbolic lattice is a free \(\mathbb Z\)-module of finite rank with an
    integral symmetric bilinear form of signature \((n,1)\) (V. V. Nikulin,
    *Reflection groups in hyperbolic spaces and the denominator formula for
    Lorentzian Kac--Moody Lie algebras*, Izvestiya: Mathematics 60 (1996), no. 2,
    arXiv:alg-geom/9503003v6, §1.1, (1.1.1) and the sentence after it, preprint
    p. 3); the opposite sign convention is that lattice with its form twisted by
    \(-1\), so both are the same object here.

    A lattice enters this category by being handed to it:
    ``HyperbolicLattices(ZZ)(L)`` checks the signature and refines ``L``,
    returning the same object with the reflection algorithms available on it.
    Arithmetic on lattices does not enter it: ``+`` returns the orthogonal sum as
    a ``Lattices`` object, as its own docstring says, and there is no uniform
    rule for it to apply here — the sum of a hyperbolic lattice with a definite
    one has signature \((n,1)\) again, while the sum of two hyperbolic lattices
    has index of inertia at least two.  So a caller that has built a sum and
    wants these methods hands the sum in.
    """

    def _repr_object_names(self):
        return f"hyperbolic lattices over {self.base_ring()}"

    def an_object(self):
        r"""The hyperbolic plane \(U\), of signature \((1,1)\)."""
        return self(Lattices(self.base_ring())("U"))

    def super_categories(self):
        return [Lattices(self.base_ring())]

    def _call_(self, lattice):
        r"""Return ``lattice`` refined into this category.

        The hypothesis is the signature: exactly one index of inertia is
        negative, or exactly one is positive.  Both spellings are hyperbolic,
        and which of them occurs is a convention about the sign of the form,
        not a fact about the geometry.
        """
        signature = lattice.signature_pair()
        positive, negative = signature.first(), signature.second()
        positive_is_one = (positive == cardinal(1)) is True
        negative_is_one = (negative == cardinal(1)) is True
        assert positive_is_one or negative_is_one, (
            f"{lattice} is not a hyperbolic lattice: a hyperbolic lattice has signature (1, n) or (n, 1), but {lattice} has signature ({positive}, {negative})"
        )
        return refine(lattice, self)

    class ParentMethods:
        def _engine_gram_of_signature_n_1(self):
            r"""Return a Gram matrix in the engine's \((n,1)\) convention.

            Returns the matrix together with whether the form was negated to
            reach that convention, since a negated form reverses every
            half-space condition and so negates the roots.
            """
            signature = self.signature_pair()
            positive, negative = signature.first(), signature.second()
            positive_is_one = (positive == cardinal(1)) is True
            negative_is_one = (negative == cardinal(1)) is True
            if negative_is_one:
                return _engine_component_matrix(self.gram_tensor()), False
            if positive_is_one:
                return _engine_component_matrix(self.twist(-1).gram_tensor()), True
            raise AssertionError(
                f"cannot run a reflection algorithm on {self}: it needs signature (1, n) or (n, 1), but {self} has signature ({positive}, {negative})"
            )

        @cached_method
        def _vinberg_search(self, controlling_vector, max_roots, max_decompositions, admits_root=None):
            r"""Run Vinberg's algorithm and return completeness with the roots.

            ``admits_root`` is the reflection-subgroup restriction of #297: a
            callable taking a root of this lattice and answering whether its
            reflection is in the subgroup.  It is applied to the candidate roots
            and to the roots of the initial cusp cone, inside the algorithm, and
            the rows are converted to lattice elements here so the caller speaks
            in elements and not in engine coordinates.

            The algorithm is stated for a lattice over any totally real ring of
            integers, where a root row is a vector over that ring and the
            height comparison is made in every real embedding.  The available
            realization works over the integers only, so the wider case is a
            stated absence rather than a silent coercion.
            """
            assert self.base_ring() is _owned_integers(), (
                f"cannot run Vinberg's algorithm on {self} over {self.base_ring()}: the "
                f"algorithm holds over any totally real ring of integers, but the "
                f"available implementation works over ZZ only.  Bottinelli's "
                f"VinbergsAlgorithmNF (github.com/bottine/VinbergsAlgorithmNF) handles "
                f"the wider case, and it is not connected here"
            )
            gram, negated = self._engine_gram_of_signature_n_1()
            coordinates = None if controlling_vector is None else list(_framing_coordinates(controlling_vector))
            row_filter = None
            if admits_root is not None:
                def row_filter(row):
                    element = self(tuple(int(entry) for entry in row))
                    return bool(admits_root(-element if negated else element))
            complete, rows = _vinal_vinberg_roots(
                gram,
                coordinates,
                max_roots,
                max_decompositions,
                admits_root=row_filter,
            )
            roots = tuple(self(tuple(int(entry) for entry in row)) for row in rows)
            return complete, tuple(-root for root in roots) if negated else roots

        def vinberg_simple_roots(self, controlling_vector=None, *, max_roots=None, max_decompositions=None, admits_root=None):
            r"""Return the roots Vinberg's algorithm accepted.

            The accepted roots are the outward normals of the walls of a
            fundamental polyhedron for \(W(L)\), taken in the order the
            algorithm's height function on the controlling vector produces
            them.  A search that ran to completion returns the whole wall set;
            a search stopped by ``max_roots`` or ``max_decompositions`` returns
            what it had, and :meth:`is_reflective` is then the proposition
            ``is_reflective(L)``.

            The controlling vector is the point of the hyperbolic space the
            enumeration measures height from.  Omitted, the engine picks one of
            negative square for itself.
            """
            _complete, roots = self._vinberg_search(
                controlling_vector, max_roots, max_decompositions, admits_root=admits_root
            )
            return finite_ordered_set(roots)

        def vinberg_algorithm(self, controlling_vector=None, *, max_roots=None, max_decompositions=None):
            r"""Return the roots accepted by Vinberg's algorithm.

            This is the archived public mathematical name for the same owned
            root family exposed by :meth:`vinberg_simple_roots`.  Historical
            engine controls such as progress output and CoxIter selection are
            not part of the mathematical operation and are deliberately not
            restored at the public boundary.
            """
            return self.vinberg_simple_roots(
                controlling_vector,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
            )

        def is_reflective(self, controlling_vector=None, *, max_roots=None, max_decompositions=None):
            r"""Return whether \(W(L)\) has finite index in \(O(L)\), or the proposition.

            Vinberg's algorithm establishes the fundamental polyhedron exactly
            when it has finite volume, so a completed search is a proof that
            the lattice is reflective.  A search that a bound stopped is not a
            proof of anything, and an unbounded search on a non-reflective
            lattice does not return, so this answers ``True`` or the
            proposition ``is_reflective(L)``, and never ``False``.  Deciding
            non-reflectivity needs Allcock's
            edgewalk, which terminates on every input; see
            :meth:`edgewalk_is_reflective`.

            In signature \((1,1)\) the criterion is unreachable: the domain is
            a half-line in \(H^1\), of infinite volume, and the question is
            refused rather than answered.
            """
            signature = self.signature_pair()
            positive, negative = signature.first(), signature.second()
            rank_one_inertia = (
                (positive == cardinal(1)) is True
                and (negative == cardinal(1)) is True
            )
            assert not rank_one_inertia, (
                f"cannot decide whether {self} is reflective: it has signature (1, 1), "
                f"where the fundamental domain is a half-line in H^1 of infinite "
                f"volume, so no polyhedron criterion applies"
            )
            complete, _roots = self._vinberg_search(controlling_vector, max_roots, max_decompositions)
            return True if complete else AtomicProposition("is_reflective", self)

        def reflection_group(self, controlling_vector=None, *, max_roots=None, max_decompositions=None):
            r"""Return \(W(L)\leq O(L)\), generated by the reflections in the roots.

            The mirrors of the walls of a fundamental polyhedron generate the
            whole reflection subgroup (Vinberg 1972), so the generators are the
            reflections in the roots :meth:`vinberg_simple_roots` returns, and
            the result is a subgroup of the owned orthogonal group rather than
            an abstract Coxeter group.  Its Coxeter presentation is read from
            :meth:`reflection_coxeter_diagram`.

            On a search that did not complete, the group generated is a
            subgroup of \(W(L)\) and need not be all of it; ask
            :meth:`is_reflective` for the certificate.
            """
            roots = self.vinberg_simple_roots(
                controlling_vector,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
            )
            return self.O().subgroup(
                [self.reflection(root) for root in roots],
                description=f"W({self})",
            )

        def weyl_group(self, controlling_vector=None, *, max_roots=None, max_decompositions=None):
            r"""Return the reflection/Weyl subgroup \(W(L)\leq O(L)\).

            ``weyl_group`` is the archived public vocabulary for the same
            subgroup now constructed by :meth:`reflection_group`; retaining
            both names does not create a second group or a second root
            enumeration.
            """
            return self.reflection_group(
                controlling_vector,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
            )

        def reflection_coxeter_diagram(self, controlling_vector=None, *, max_roots=None, max_decompositions=None):
            r"""Return the Coxeter diagram of the fundamental polyhedron.

            One vertex per wall, rooted in the accepted roots, so the diagram
            carries the exact pairings and separates parallel walls from
            divergent ones.  It is the diagram of \(W(L)\) as a Coxeter group
            when the search completed.
            """
            from sage_extensions.categories.coxeter_diagrams import (
                CoxeterDiagrams,
            )

            roots = self.vinberg_simple_roots(
                controlling_vector,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
            )
            return CoxeterDiagrams().from_roots(finite_indexed_family_from_values(None, tuple(roots)))

        def _chamber_vertex_squares(self, controlling_vector, max_roots, max_decompositions):
            r"""Return the squares of the vertices of the fundamental polyhedron.

            The chamber is \(\{x : b(x,r)\leq 0\text{ for every wall } r\}\),
            which in coordinates is the cone dual to the one spanned by the
            rows \(rG\).  Its extreme rays are the vertices of the polyhedron,
            and the square of a ray decides its kind: nonzero inside the light
            cone — negative or positive according as the lattice's form presents
            the component, \((n,1)\) or \((1,n)\) — and zero on the cone, so an
            ideal point of the boundary.  That is why `is_cocompact` reads only
            whether a square is zero.

            One ring carries the computation: the lattice's private engine ring
            (:func:`_engine_element`).  The Gram, the wall normals and the
            polyhedral cone are engine data, the framing coordinates arrive
            lowered (:func:`_framing_coordinates`), and each vertex ray is raised
            back into the owned ring only for the final contraction.
            """
            from sage.geometry.cone import Cone

            gram = _engine_component_matrix(self.gram_tensor())
            _complete, roots = self._vinberg_search(controlling_vector, max_roots, max_decompositions)
            wall_normals = [engine_vector(_framing_coordinates(root)) * gram for root in roots]
            chamber = Cone(wall_normals).dual()
            ring = self.base_ring()
            gram_tensor = self.gram_tensor()
            vertices = (
                tensor.vector(ring, [_owned_engine_element(ring, coordinate) for coordinate in ray])
                for ray in chamber.rays()
            )
            return tuple(gram_tensor.contract(vertex, vertex) for vertex in vertices)

        def _full_chamber_vertices(self):
            r"""Return the vertex data of the chamber of the full reflection group.

            Each entry of the returned tuple is a quadruple: the ray's framing
            coordinates (a tuple of integers, one per generator of the framing,
            in the engine's coordinate order), its square in this lattice's own
            form (positive for a finite vertex of the hyperbolic space, zero for
            an ideal vertex of the light cone), and the wall roots of the full
            group's chamber that pass through the vertex -- those are the roots
            orthogonal to it, one pairing of the ray's coordinates with a wall
            normal -- and whether those walls are a \(\mathbf Z\)-basis of the
            vertex's orthogonal complement, their Gram determinant against the
            determinant of that complement computed as the Gram determinant of
            the kernel of the pairing row, which is the engine's own \(M_1\)
            for the vertex as a controlling vector.

            The chamber of the full reflection group is the one Vinberg's
            algorithm computes with no reflection-subgroup restriction
            (:meth:`fundamental_chamber` with no ``admits_root``), and its
            vertices are the extreme rays of the cone dual to that spanned by
            the wall normals: the same construction
            :meth:`_chamber_vertex_squares` reads the squares of.  A vertex of
            that chamber lies in every chamber of a reflection subgroup of
            \(W(L)\), because the subgroup's chamber contains the full group's
            -- a group generated by fewer reflections cuts out a bigger
            polyhedron -- so a caller that anchors a subgroup-restricted search
            at such a vertex asks for the subgroup's own chamber back: Vinberg
            1972, §3.2, the construction after Proposition 3 (p. 27) -- the
            unique cell of \(\Gamma\) coinciding with \(P_0\) near \(p_0\) --
            with Proposition 4 (p. 28: the polyhedron cut out by the listed
            normals is that cell) and Proposition 5 (p. 29: the finite-volume
            termination).  The controlling vector computed from these vertices
            therefore needs no separate certificate of giving the same chamber.
            """
            from sage.geometry.cone import Cone

            engine_gram, negated = self._engine_gram_of_signature_n_1()
            _complete, roots = self._vinberg_search(None, None, None)
            wall_coordinates = [engine_vector(_framing_coordinates(root)) for root in roots]
            wall_normals = [coordinate * engine_gram for coordinate in wall_coordinates]
            chamber = Cone(wall_normals).dual()
            library_gram = _engine_component_matrix(self.gram_tensor())
            vertices = []
            for ray in chamber.rays():
                coordinates = engine_vector(SageQQ, [int(entry) for entry in ray])
                square = coordinates * library_gram * coordinates
                orthogonal = [
                    position
                    for position, normal in enumerate(wall_normals)
                    if coordinates.dot_product(normal) == 0
                ]
                normals = [wall_coordinates[position] for position in orthogonal]
                gram_of_walls = engine_matrix(
                    [[int(u * engine_gram * v) for v in normals] for u in normals]
                )
                kernel = engine_matrix([coordinates * engine_gram]).right_kernel()
                kernel_basis = kernel.matrix()
                complement_gram = kernel_basis * engine_gram * kernel_basis.transpose()
                vertices.append(
                    (
                        tuple(int(entry) for entry in ray),
                        square,
                        tuple(roots[position] for position in orthogonal),
                        int(abs(gram_of_walls.det())) == int(abs(complement_gram.det())),
                    )
                )
            return tuple(vertices)

        def is_cocompact(self, controlling_vector=None, *, max_roots=None, max_decompositions=None):
            r"""Return whether \(W(L)\) acts cocompactly, or the proposition ``is_cocompact(L)``.

            A fundamental polyhedron is compact exactly when it has finite
            volume and no ideal vertex.  Finite volume is
            :meth:`is_reflective`; an ideal vertex is a vertex of square zero,
            lying on the light cone rather than inside it.  Stated on the
            squares rather than on their sign, the criterion does not depend on
            which sign convention the form carries.

            Not cocompact does not mean infinite covolume: a reflective lattice
            with an ideal vertex has a finite-volume noncompact fundamental
            domain, which is the common hyperbolic case.
            """
            reflective = self.is_reflective(
                controlling_vector,
                max_roots=max_roots,
                max_decompositions=max_decompositions,
            )
            if reflective is not True:
                return AtomicProposition("is_cocompact", self)
            return all(square != 0 for square in self._chamber_vertex_squares(controlling_vector, max_roots, max_decompositions))

