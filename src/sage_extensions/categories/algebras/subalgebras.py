r"""The ``R``-subalgebra generated by a family of homogeneous elements.

``Algebra.adjoin R s`` is the smallest ``R``-subalgebra containing ``s``
(Mathlib, ``Algebra/Algebra/Subalgebra/Lattice.lean:35``:
``adjoin R s = Subsemiring.closure (Set.range (algebraMap R A) ∪ s)``, with the
universal property ``Algebra.gc`` and the closure induction
``adjoin_induction``).  Its points are the ``R``-span of the words in ``s``,
together with ``1``.

In a graded algebra with *homogeneous* generators of positive degree, the
degree-``d`` part of that span is spanned by the finitely many products of
generators whose degrees sum to ``d``, because a product of homogeneous elements
is homogeneous of the summed degree.  That is what makes the construction
decidable: the words of one degree are finite, and membership in their span is
the maintained image test of a module morphism.

``gamma_2(x)`` in ``Gamma(ZZ[x])`` is the specimen.  A word in ``x`` of degree
``n`` is ``x^n = n! gamma_n(x)``, so ``x*x = 2 gamma_2(x)`` lies in the
subalgebra generated by ``x`` and ``gamma_2(x)`` does not: no integer ``c`` has
``2c = 1``.  The decision below answers exactly that, over ``ZZ``, in a torsion
piece as well as in a free one, and it invents no linear algebra: degree by
degree it asks ``is_in_image`` of ``F(words_d) -> A_d``, which the selected
Smith normal form of the graded piece decides.
"""

from sage.misc.cachefunc import cached_function, cached_method

from sage_extensions.categories.algebras.graded_algebras import (
    GradedAlgebras,
    _graded_multiplication_from_components,
)
from sage_extensions.categories.modules.graded_modules import GradedModules
from sage_extensions.categories.modules.pure.modules import ModuleSubobjects
from sage_extensions.categories.rings.ring_foundation import OwnedCategoryOverBaseRing
from sage_extensions.categories.sets.indexed_families import indexed_family
from sage_extensions.categories.sets.set_categories import NN, Sets


def _homogeneous_generators(algebra, elements):
    r"""Read the generating family as homogeneous elements of positive degree.

    ``adjoin`` is stated for any set, and its realization here is the graded
    one: a nonhomogeneous generator would need the words of one degree to
    mention it in several degrees at once.  Zero generates nothing and is
    dropped; a degree-zero generator contributes only scalars, and the generated
    degree-zero part is the scalar copy ``R`` that ``1`` already spans.
    """
    generators = []
    for element in elements:
        generator = algebra(element)
        if (generator == algebra.zero()) is True:
            continue
        homogeneous = generator.is_homogeneous()
        assert homogeneous is True, (
            f"the subalgebra generated by {generator} is computed here from the graded words, "
            "which needs homogeneous generators"
        )
        degree = int(generator.degree())
        if degree == 0:
            raise NotImplementedError(
                f"the subalgebra generated by degree-zero elements is not decided here: "
                f"{generator} lies in degree 0, where the generated part is not a span of words"
            )
        generators.append((degree, generator))
    return tuple(generators)


def _words_of_degree(generators, degree):
    r"""The ordered words in ``generators`` whose degrees sum to ``degree``.

    A tuple of tuples of positions.  Degree zero is the empty word, whose
    product is ``1``.  Finitely many because every generator degree is positive,
    which is why this realization needs them.
    """
    found = []
    prefix = []

    def extend(remaining):
        if remaining == 0:
            found.append(tuple(prefix))
            return
        for position, (generator_degree, _) in enumerate(generators):
            if generator_degree <= remaining:
                prefix.append(position)
                extend(remaining - generator_degree)
                prefix.pop()

    extend(int(degree))
    return tuple(found)


def _word_product(algebra, generators, degree):
    r"""The product of each word of ``degree``, in the ambient algebra.

    Ambient elements, not piece elements: the degree-zero piece is the scalar
    ring itself, so a product of two piece elements of degree zero is a scalar
    rather than a member of the piece.  Reading the component where a piece
    element is needed keeps the arithmetic in the one algebra.
    """
    if int(degree) == 0:
        return (algebra.one(),)
    products = []
    for word in _words_of_degree(generators, degree):
        product = algebra.one()
        for position in word:
            product = product * generators[position][1]
        # Ordered words repeat each other (``(x, y)`` and ``(y, x)`` multiply to
        # the same product in a commutative algebra), and a repeated generator
        # spans nothing new.  Keeping one of each equal product states the same
        # span without handing the integral preimage solver a redundant family.
        if any((product == kept) is True for kept in products):
            continue
        products.append(product)
    return tuple(products)


def _span_morphism(algebra, generators, degree):
    r"""``F(words_d) -> A_d`` sending each word of ``degree`` to its product."""
    ring = algebra.algebra_base_ring()
    piece = algebra.graded_piece(degree)
    products = _word_product(algebra, generators, degree)
    labels = Sets.Δ[len(products) - 1]
    source = ring.free_module(labels)
    return source.module_category().Mor(source, piece)(
        {
            label: products[int(label)].homogeneous_components()[int(degree)]
            for label in labels
        }
    )


def _closure_defect(algebra, generators):
    r"""Return the first word product outside the spans, or ``None``.

    The generated set is a subalgebra exactly when a product of two spanned
    elements is spanned, and because the spans are generated by words it is
    enough that a product of two *words* lies in the span of the words of the
    summed degree.  Each decision is `is_in_image`, so a wrongly enumerated word
    family is refused here rather than silently accepted.
    """
    if not generators:
        return None
    # A product of two words is the product of the concatenated word, so the
    # enumeration is consistent exactly when each pair of words *of generator
    # degrees* multiplies into the span of the summed degree; longer words are
    # concatenations of those.
    bound = max(generator_degree for generator_degree, _ in generators)
    for left_degree in range(bound + 1):
        for right_degree in range(bound + 1):
            target = _span_morphism(algebra, generators, left_degree + right_degree)
            for left in _word_product(algebra, generators, left_degree):
                for right in _word_product(algebra, generators, right_degree):
                    total = left_degree + right_degree
                    component = (left * right).homogeneous_components()[total]
                    if target.is_in_image(component) is not True:
                        return (
                            f"the product of a degree-{left_degree} word with a degree-"
                            f"{right_degree} one is {component}, which the degree-{total} words "
                            "do not span"
                        )
    return None


class GeneratedSubalgebras(OwnedCategoryOverBaseRing):
    r"""The ``R``-subalgebras generated by finitely many homogeneous elements.

    An object is an algebra in its own right -- the graded direct sum of the
    degree pieces ``W_d``, each the *image* of the module morphism
    ``F(words_d) -> A_d`` -- together with the inclusion ``W -> A`` as an
    algebra morphism.  That is the categorical shape of a subobject (``ARC-07``,
    ``OWN-15``): the way ``Subgroups(G)`` returns a group with an inclusion and
    ``ModuleSubobjects(R)`` a module with an inclusion, never a predicate
    carrier standing in for the object.

    Membership of an *ambient* element is asked through the retained degree
    inclusions, which is the same exact decision the accepted arithmetic
    specimens state: ``gamma_2(x)`` is in the subalgebra generated by ``x`` over
    ``QQ`` and not over ``ZZ``.
    """

    def an_object(self):
        r"""``ZZ[x]`` inside ``ZZ[x]``, generated by its indeterminate."""
        from sage_extensions.categories.modules.pure.modules import Modules

        polynomials = Modules(self.base_ring()).free_module(("x",)).symmetric_algebra()
        label = next(iter(polynomials.algebra_generating_set()))
        return _generated_subalgebra(polynomials, [polynomials.algebra_generator(label)])

    def _repr_object_names(self):
        return f"generated subalgebras over {self.base_ring()}"

    def super_categories(self):
        return [GradedAlgebras(self.base_ring())]

    class ParentMethods:
        def __init__(
            self,
            subalgebra_ambient=None,
            subalgebra_generators=None,
            **rest,
        ) -> None:
            self._preamble_subalgebra_ambient = subalgebra_ambient
            self._preamble_subalgebra_generators = subalgebra_generators
            super().__init__(**rest)

        def ambient_algebra(self):
            r"""Return the algebra this one is a subalgebra of."""
            return self._preamble_subalgebra_ambient

        def ambient_ring(self):
            r"""The ambient algebra, under the predicate-subring accessor's name."""
            return self.ambient_algebra()

        def generators(self):
            r"""Return the retained generating family, in the order it was given."""
            return self._preamble_subalgebra_generators

        def algebra_generators(self):
            r"""The retained generating family, under the algebra owner's name."""
            return self.generators()

        def defining_predicate(self):
            r"""Return membership in the subalgebra, as a function of ambient elements.

            This is the semantic content the predicate-subring vehicle exposed,
            now stated by the object that owns the inclusions.
            """
            return lambda element: element in self

        @cached_method
        def _generator_pairs(self):
            r"""The retained generators as ``(degree, element)`` pairs."""
            return _homogeneous_generators(self.ambient_algebra(), self.generators())

        @cached_method
        def degree_inclusion(self, degree):
            r"""Return the retained inclusion ``W_d -> A_d`` of one degree piece."""
            return _degree_data(self.ambient_algebra(), self._generator_pairs(), int(degree))[1]

        @cached_method
        def inclusion(self):
            r"""Return ``W -> A``, the inclusion of this subalgebra as an algebra morphism.

            On a homogeneous component of ``W`` it is that degree's module
            inclusion followed by the ambient component's own placement; the
            construction is unital and multiplicative because the product on
            ``W`` is transported through these same inclusions.
            """
            from sage_extensions.categories.algebras.comparison_maps import (
                _constructed_algebra_morphism,
            )

            ambient = self.ambient_algebra()

            def evaluate(element):
                return sum(
                    (
                        ambient.from_component(
                            int(degree), self.degree_inclusion(int(degree))(component)
                        )
                        for degree, component in self(element).homogeneous_components().items()
                    ),
                    ambient.zero(),
                )

            return _constructed_algebra_morphism(self, ambient, evaluate)

        def __contains__(self, element):
            r"""Whether an *ambient* element lies in this subalgebra, decided by degrees.

            An element this subalgebra constructed is a member by construction;
            an ambient element is decided componentwise, in its own degree's
            image subobject, which is the maintained ``ModuleSubobjects``
            membership and therefore the same arithmetic as before.
            """
            from sage.structure.element import parent as element_parent

            if element_parent(element) is self:
                return True
            ambient = self.ambient_algebra()
            if element not in ambient:
                return False
            candidate = ambient(element)
            for degree, component in candidate.homogeneous_components().items():
                piece = _degree_data(ambient, self._generator_pairs(), int(degree))[0]
                if (component in piece) is not True:
                    return False
            return True

        is_parent_of = __contains__


@cached_function(
    key=lambda algebra, generators, degree: (
        algebra,
        tuple(generator for _, generator in generators),
        int(degree),
    )
)
def _degree_data(algebra, generators, degree):
    r"""Return ``(W_degree, inclusion)`` for ``(degree, element)`` generators.

    The generators are the pairs :func:`_homogeneous_generators` returns; the
    degree's words are formed from them, so the family must be that form.

    The image is taken through the maintained ``image_factorization`` of the
    word morphism ``F(words_d) -> A_d``, so ``W_d`` is a module subobject with
    its inclusion, not a new carrier.

    Cached by the ambient algebra, its generating family and the degree: one
    subalgebra must see *one* object per degree piece, because the graded sum
    coerces an element of a degree piece into ``graded_piece(d)``, and two
    separately built images of the same words are two different parents.
    """
    ring = algebra.algebra_base_ring()
    if int(degree) < 0:
        empty = ring.free_module(0)
        return empty, empty.module_category().Mor(empty, empty).identity()
    morphism = _span_morphism(algebra, generators, int(degree))
    _factorization, inclusion = morphism.image_factorization()
    return inclusion.domain(), inclusion


def _generated_subalgebra(algebra, elements):
    r"""Return the subalgebra of ``algebra`` generated by ``elements``.

    The result is an ``R``-algebra with an algebra-morphism inclusion into
    ``algebra`` -- the categorical shape of a subobject (``ARC-07``,
    ``OWN-15``), the way ``Subgroups(G)`` returns a group with an inclusion.

    See :class:`GeneratedSubalgebras`: the result is an ``R``-algebra with an
    algebra-morphism inclusion into ``algebra``, whose degree pieces are the
    images of the word morphisms and whose product is transported through those
    inclusions.
    """
    from sage_extensions.categories.algebras.algebras import _algebra_on_module

    ring = algebra.algebra_base_ring()
    generators = _homogeneous_generators(algebra, elements)
    defect = _closure_defect(algebra, generators)
    assert defect is None, (
        f"the words in {[generator for _, generator in generators]} do not span a subalgebra "
        f"of {algebra}: {defect}"
    )

    graded = GradedModules(ring)
    monoid = graded.grading_monoid()

    def piece(degree):
        return _degree_data(algebra, generators, int(degree))[0]

    module = graded(indexed_family(monoid, piece), componentwise_framing=True)

    def read_into(degree, ambient_component):
        target, inclusion = _degree_data(algebra, generators, int(degree))
        if inclusion.has_selected_lift():
            return target(inclusion.lift(ambient_component))
        return target(ambient_component)

    def component_product(left_degree, left, right_degree, right):
        r"""Multiply through the degree inclusions and read the product back.

        ``_graded_multiplication_from_components`` supplies elements of the
        *subalgebra's* pieces ``W_i`` and expects an element of ``W_{i+j}``, so
        the two carriers are never identified: ``inclusion_i: W_i -> A_i``
        places each factor in the ambient algebra, the product is taken there,
        and ``inclusion_{i+j}`` reads it back into ``W_{i+j}``.
        """
        total = int(left_degree) + int(right_degree)
        left_ambient = algebra.from_component(
            int(left_degree), _degree_data(algebra, generators, int(left_degree))[1](left)
        )
        right_ambient = algebra.from_component(
            int(right_degree), _degree_data(algebra, generators, int(right_degree))[1](right)
        )
        product = left_ambient * right_ambient
        return read_into(total, product.homogeneous_components()[total])

    multiplication = _graded_multiplication_from_components(module, component_product)
    # The unit is the image of the empty word, which is ``W_0``'s canonical
    # generator; it is never read back from an ambient element.  Over ``QQ`` the
    # degree-zero piece is a localization of a ZZ module, whose element
    # constructor takes elements of *its* numerator module rather than of the
    # rational piece, so reading the ambient ``1`` into it is a carrier
    # identification the two objects do not have.
    unit_piece = _degree_data(algebra, generators, 0)[0]
    unit = module.from_component(
        0, unit_piece.module_generator(next(iter(unit_piece.module_generating_set())))
    )
    return _algebra_on_module(
        module,
        multiplication,
        placement=(GeneratedSubalgebras(ring),),
        unit=unit,
        construction_data={
            "subalgebra_ambient": algebra,
            "subalgebra_generators": tuple(generator for _, generator in generators),
        },
        law_decisions={"associativity": True, "unit": True, "grading": True},
    )

