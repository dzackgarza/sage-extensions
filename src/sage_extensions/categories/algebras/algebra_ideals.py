r"""The two-sided ideal of a graded algebra generated by degree-one elements.

An ideal generated by *homogeneous* elements is graded.  With
:math:`A = \bigoplus_d A_d` and :math:`K \subseteq A_1`, every sum of products
:math:`x k y` with :math:`x, y` homogeneous has its terms of one degree, and a
two-sided ideal is exactly a sum of such products, so

.. math:: I_d = \sum_{i + j = d - 1} A_i K A_j .

Because :math:`A_i` and :math:`A_j` carry finite chosen frames in the
constructions below, that family is finite in each degree, and the degree
submodule :math:`I_d` is the *image* of the module morphism
:math:`F(\text{that family}) \to A_d`.  Membership is therefore the maintained
integral image test of a framed module morphism, degree by degree, and no second
normal-form algorithm is introduced.

A divided-power algebra carries a second, larger ideal.  :math:`\gamma_j(k)` is
not a polynomial in :math:`k` over :math:`\ZZ`, so the relations a presentation
of :math:`\Gamma(M)` states are the *divided-power* ones: the degree-``d`` part
of the divided-power ideal generated by ``K`` also contains
:math:`\gamma_j(k) A_{d-j}` for :math:`2 \le j \le d` (Stacks Tag 07GL; the
multiplication ``dp_mul`` of ``DividedPowers4``,
``github.com/AntoineChambert-Loir/DividedPowers4``, ``DPAlgebra/Init.lean:192``).
That is the ideal the existing ``ideal_generators_in_degree`` names for divided
powers, and it is strictly larger than the ordinary one.

The specimen is :math:`\Gamma(\ZZ x)` and :math:`k = 2x`.  In degree three
:math:`\gamma_3(2x) = 8\gamma_3(x)` while the ordinary ideal generated by
:math:`2x` meets degree three in :math:`2x \cdot \ZZ\gamma_2(x) = 6\ZZ\gamma_3(x)`:
``8 gamma_3(x)`` is in the divided-power ideal and not in the ordinary one, and
``6 gamma_3(x)`` is in both.  Every number there is decided by the retained
product and framing, not by a separate polynomial normal form.
"""

from sage.misc.cachefunc import cached_function, cached_method

from sage_extensions.categories.modules.graded_modules import GradedModules
from sage_extensions.categories.rings.ring_foundation import OwnedCategoryOverBaseRing
from sage_extensions.categories.sets.indexed_families import indexed_family
from sage_extensions.categories.sets.set_categories import Sets


def _degree_one_generators(algebra, elements):
    r"""Read the generating family as degree-one elements of the algebra.

    The construction is graded and stated for generators of degree one: a
    degree-``n`` generator would contribute :math:`x k y` in degrees at least
    ``n``, and an element of mixed degree would need the products of its parts.
    Neither is refused as mathematics -- only as this realization's input.
    """
    generators = []
    for element in elements:
        generator = algebra(element)
        if (generator == algebra.zero()) is True:
            continue
        homogeneous = generator.is_homogeneous()
        assert homogeneous is True, (
            f"the ideal generated by {generator} is computed here degreewise, which needs "
            "homogeneous generators"
        )
        degree = int(generator.degree())
        if degree != 1:
            raise NotImplementedError(
                f"the ideal of {algebra} generated by {generator} is not decided here: this "
                f"construction is stated for generators in degree 1, but {generator} lies in "
                f"degree {degree}"
            )
        generators.append(generator)
    return tuple(generators)


def _degree_basis(algebra, degree):
    r"""The chosen frame of ``A_degree``, realized as ambient algebra elements.

    Degree zero is the scalar copy, whose frame is the unit; its piece is the
    regular module of the coefficient ring, not a module of the algebra, so it
    is named rather than read.
    """
    degree = int(degree)
    if degree == 0:
        return (algebra.one(),)
    piece = algebra.graded_piece(degree)
    labels = piece.module_generating_set()
    assert labels.cardinality().is_finite() is True, (
        f"the ideal generated in degree one is computed degreewise, which needs a finite chosen "
        f"frame of {piece}, but it has {labels.cardinality()}"
    )
    return tuple(
        algebra.from_component(degree, piece.module_generator(label)) for label in labels
    )


def _degree_generators(algebra, generators, degree, divided_powers):
    r"""The finite family spanning ``I_degree``: ``x k y``, and ``gamma_j(k) y``.

    In a graded-commutative algebra the one-sided products would already span
    the two-sided ideal for generators of degree one; the products are written
    on both sides so that the statement does not depend on that identification.
    Equal products are kept once: a repeated generator hands the integral
    preimage solver a redundant family without stating anything new.
    """
    degree = int(degree)
    found = []
    for generator in generators:
        for left_degree in range(degree):
            right_degree = degree - 1 - left_degree
            for left in _degree_basis(algebra, left_degree):
                for right in _degree_basis(algebra, right_degree):
                    found.append(
                        (left * generator * right).homogeneous_component(degree)
                    )
    if divided_powers:
        for generator in generators:
            for exponent in range(2, degree + 1):
                power = algebra.divided_power(generator, exponent)
                for complementary in _degree_basis(algebra, degree - exponent):
                    found.append((power * complementary).homogeneous_component(degree))
    kept = []
    for element in found:
        if (element == algebra.zero()) is True:
            continue
        if any((element == other) is True for other in kept):
            continue
        kept.append(element)
    return tuple(kept)


def _span_morphism(algebra, generators, degree, divided_powers):
    r"""``F(generators of I_degree) -> A_degree``, one generator to its element."""
    ring = algebra.algebra_base_ring()
    piece = algebra.graded_piece(int(degree))
    elements = _degree_generators(algebra, generators, int(degree), divided_powers)
    labels = Sets.Δ[len(elements) - 1]
    source = ring.free_module(labels)
    return source.module_category().Mor(source, piece)(
        {label: elements[int(label)] for label in labels}
    )


class GeneratedAlgebraIdeals(OwnedCategoryOverBaseRing):
    r"""The two-sided ideals of a graded algebra generated by degree-one elements.

    An object is a graded submodule :math:`I = \bigoplus_d I_d` of its ambient
    algebra together with the inclusion :math:`I \to A` -- the categorical
    shape of a subobject (``ARC-07``, ``OWN-15``), as ``GeneratedSubalgebras``
    carries for the subalgebra generated by homogeneous elements.  The
    divided-power flavor adds ``gamma_j(k) A_{d-j}`` to each degree, which is
    what separates the two ideals of a divided-power algebra.
    """

    def an_object(self):
        r"""``(2x)`` inside :math:`\Gamma(\ZZ x)`, as a divided-power ideal."""
        from sage_extensions.categories.modules.pure.modules import Modules

        algebra = Modules(self.base_ring()).free_module(("x",)).divided_power_algebra()
        label = next(iter(algebra.generating_module().module_generating_set()))
        generator = algebra.degree_one_generator(label)
        return _generated_algebra_ideal(
            algebra, [self.base_ring()(2) * generator], divided_powers=True
        )

    def _repr_object_names(self):
        return f"ideals of graded algebras over {self.base_ring()} generated in degree one"

    def super_categories(self):
        return [GradedModules(self.base_ring())]

    class ParentMethods:
        def __init__(
            self,
            ideal_ambient_algebra=None,
            ideal_generators=None,
            ideal_divided_powers=None,
            **rest,
        ) -> None:
            self._preamble_ideal_ambient = ideal_ambient_algebra
            self._preamble_ideal_generators = ideal_generators
            self._preamble_ideal_divided_powers = ideal_divided_powers
            super().__init__(**rest)

        def ambient_algebra(self):
            r"""The algebra this ideal is a submodule of, with its own product."""
            return self._preamble_ideal_ambient

        def generators(self):
            r"""The retained degree-one generators, in the order they were given."""
            return self._preamble_ideal_generators

        def algebra_generators(self):
            r"""The retained generating family, under the algebra owner's name."""
            return self.generators()

        def is_divided_power_ideal(self):
            r"""Whether this is the divided-power ideal rather than the ordinary one."""
            return self._preamble_ideal_divided_powers

        def _repr_(self):
            r"""Name the ideal, its generators and its ambient algebra.

            Two ideals of one algebra differ only in that data, so the graded
            sum's own name would make them indistinguishable in a traceback.
            """
            generators = ", ".join(str(generator) for generator in self.generators())
            flavor = "divided power ideal" if self.is_divided_power_ideal() else "ideal"
            return f"{flavor} ({generators}) of {self.ambient_algebra()}"

        @cached_method
        def degree_inclusion(self, degree):
            r"""The inclusion ``I_degree -> A_degree`` of one graded piece."""
            return _ideal_degree_data(
                self.ambient_algebra(),
                self.generators(),
                int(degree),
                self.is_divided_power_ideal(),
            )[1]

        def _degree_component_inclusion(self, degree):
            r"""The summand inclusion ``I_degree -> A`` that ``graded_piece`` states."""
            from sage_extensions.categories.modules.pure.modules import Modules

            ambient = self.ambient_algebra()
            ring = ambient.algebra_base_ring()
            return Modules(ring).Mor(self.graded_piece(int(degree)), ambient)._from_constructed_element_map(
                lambda element: ambient.from_component(
                    int(degree), self.degree_inclusion(int(degree))(element)
                )
            )

        @cached_method
        def inclusion(self):
            r"""Return ``I -> A``, the submodule inclusion restricted to each degree.

            A graded submodule is the direct sum of its pieces, so the map is
            the unique one whose restriction to ``I_d`` is that degree's
            inclusion followed by ``A``'s own summand placement.
            """
            ambient = self.ambient_algebra()
            graded = GradedModules(ambient.algebra_base_ring())
            return self.from_maps(
                ambient,
                indexed_family(
                    graded.grading_monoid(), self._degree_component_inclusion
                ),
            )

        def __contains__(self, element):
            r"""Whether an ambient element lies in this ideal, decided by degrees.

            An element of the ideal itself is a member by construction. An
            ambient element is decided componentwise, each component in its own
            degree's image subobject -- the maintained ``ModuleSubobjects``
            membership, and therefore the same integral arithmetic the graded
            piece already owns.
            """
            from sage.structure.element import parent as element_parent

            if element_parent(element) is self:
                return True
            ambient = self.ambient_algebra()
            if element not in ambient:
                return False
            candidate = ambient(element)
            for degree, component in candidate.homogeneous_components().items():
                piece = _ideal_degree_data(
                    ambient,
                    self.generators(),
                    int(degree),
                    self.is_divided_power_ideal(),
                )[0]
                if (component in piece) is not True:
                    return False
            return True


@cached_function(
    key=lambda algebra, generators, degree, divided_powers: (
        algebra,
        tuple(generators),
        int(degree),
        bool(divided_powers),
    )
)
def _ideal_degree_data(algebra, generators, degree, divided_powers):
    r"""Return ``(I_degree, inclusion)`` for one degree of the generated ideal.

    Cached by the ambient algebra, its generating family, the degree and the
    flavor: one ideal must see *one* subobject per degree, because the graded
    sum coerces an element of a degree piece into ``graded_piece(d)``, and two
    separately built images of the same family are two different parents.
    """
    ring = algebra.algebra_base_ring()
    if int(degree) < 0:
        empty = ring.free_module(0)
        return empty, empty.module_category().Mor(empty, empty).identity()
    morphism = _span_morphism(algebra, generators, int(degree), divided_powers)
    _factorization, inclusion = morphism.image_factorization()
    return inclusion.domain(), inclusion


def _generated_algebra_ideal(algebra, elements, *, divided_powers):
    r"""The ideal of ``algebra`` generated by degree-one ``elements``.

    The result is a graded submodule with a module-morphism inclusion into
    ``algebra``; for ``divided_powers`` each degree also contains the divided
    powers of the generators, which is the ideal a divided-power presentation
    states its relations in.
    """
    ring = algebra.algebra_base_ring()
    generators = _degree_one_generators(algebra, elements)
    graded = GradedModules(ring)
    monoid = graded.grading_monoid()

    def piece(degree):
        return _ideal_degree_data(algebra, generators, int(degree), divided_powers)[0]

    module = graded(indexed_family(monoid, piece), componentwise_framing=True)
    return module._module_with_structure(
        (GeneratedAlgebraIdeals(ring),),
        {
            "ideal_ambient_algebra": algebra,
            "ideal_generators": generators,
            "ideal_divided_powers": bool(divided_powers),
        },
    )
