r"""The pinned card digest, read by tag.

The numbers the Enriques acceptance compares against are not typed into a test:
they are the rows of ``dzackgarza/lattice-database``, fetched at one database
commit into ``tests/cards/lattice-database-enriques.json`` by
``tests/cards/refresh_lattice_database_enriques.py``, which records the commit it
used and refuses a ref that is not a full SHA.  This module is the reader of that
digest, so a test can name a card by tag and not restate its number.

Nothing here decides anything about a lattice: it returns the card's own
recorded row, and the card's ``reference.citation`` names the paper, table and
printed page the row comes from.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

DIGEST = (
    Path(__file__).resolve().parents[2] / "tests" / "cards" / "lattice-database-enriques.json"
)


def _digest():
    r"""Return the parsed digest, or raise naming the file it could not read."""
    if not DIGEST.exists():
        raise FileNotFoundError(
            f"the Enriques card digest {DIGEST} is not present: it is generated by "
            f"tests/cards/refresh_lattice_database_enriques.py --ref <database commit>"
        )
    return json.loads(DIGEST.read_text())


def _orbit_rows(tag: str):
    r"""Return ``(rows, source)``: the orbit rows card ``tag`` states, and who states them.

    A lattice card keeps them under ``integral.primitive_orbits`` and the digest
    stores them per group; an arithmetic-group card states the singular rows
    ``data.line_orbits``, ``data.plane_orbits`` and ``data.flag_orbits``, which the
    digest stores under the card's tag.  One resolution serves the readers below,
    so two rows of the same card cannot be read from different cards.
    """
    digest = _digest()
    lattice_rows = digest.get("plane_orbits", {})
    if tag in lattice_rows:
        return lattice_rows[tag]["rows"], f"lattice card {tag}"
    rows = {
        name: {"planes": card["plane_orbits"], "lines": card["line_orbits"]}
        for name, card in digest.get("arithmetic_groups", {}).items()
        if card.get("tag") == tag
    }
    return rows, f"arithmetic-group card {tag}"


def card_plane_orbit_row(tag: str, group: str) -> int:
    r"""Return card ``tag``'s number of primitive isotropic plane orbits under ``group``.

    The row is ``integral.primitive_orbits.{group}.planes`` of the lattice card,
    or ``data.plane_orbits`` of an arithmetic-group card; both are what the
    digest keeps.  A card that states no such row raises, rather than returning
    a number of another group's.
    """
    rows, source = _orbit_rows(tag)
    if group not in rows:
        raise KeyError(
            f"{source} states no primitive-isotropic-plane row for {group!r}: "
            f"it states {sorted(rows)}"
        )
    if "planes" not in rows[group]:
        raise KeyError(
            f"{source} states a row for {group!r} without a plane count: it states "
            f"{sorted(rows[group])}"
        )
    return rows[group]["planes"]


def card_line_orbit_row(tag: str, group: str) -> int:
    r"""Return card ``tag``'s number of primitive isotropic line orbits under ``group``.

    The row is the card's ``integral.primitive_orbits.{group}.constant``, stored by
    the digest as ``lines``: a card's ``constant`` is the number of its
    0-dimensional cusps, and those cusps are the primitive isotropic *lines*.  On
    ``029J`` the ``Otilde+`` row states **528** lines beside 24242 planes for
    ``Otilde^+(N)`` on ``N = U + U(2) + E8(-2)`` -- "the space M~_En =
    Otilde^+(N)\D_N ... has 528 0-dimensional cusps (isotropic lines) and 24242
    1-dimensional cusps (isotropic planes); under O^+_10(F_2) the 528 lines fall in
    two orbits, of lengths 527 and 1" (D. Dutour Sikirić, K. Hulek, *Moduli of
    polarised Enriques surfaces -- computational aspects*, arXiv:2302.01679v2,
    Section 3.6).  Its ``O`` row states 2: Sterk's two orbits of primitive
    isotropic lines (*Compactifications of the period space of Enriques surfaces,
    Part I*, Math. Z. 207 (1991), Proposition 4.5).

    A card that states no such row raises, rather than returning another group's
    count.
    """
    rows, source = _orbit_rows(tag)
    if group not in rows:
        raise KeyError(
            f"{source} states no primitive-isotropic-line row for {group!r}: "
            f"it states {sorted(rows)}"
        )
    if "lines" not in rows[group]:
        raise KeyError(
            f"{source} states a row for {group!r} without a line count: it states "
            f"{sorted(rows[group])}"
        )
    return rows[group]["lines"]


def card_plane_orbit_lengths(tag: str, group: str):
    r"""Return card ``tag``'s per-orbit numbers for the primitive isotropic planes under ``group``.

    The row's ``orbit_lengths`` field is the card's own record of the sizes of
    those orbits, in the order its citation names them
    (``integral.primitive_orbits.{group}.orbit_lengths`` on the card, which
    ``tests/cards/refresh_lattice_database_enriques.py`` emits as the row's
    ``orbit_lengths``): the lattice-database card states it for
    ``029J``'s ``O`` and ``Otilde+`` rows, 527 and 23715, beside the row total and
    the row's count of orbits.  Nothing here parses a sentence.

    The reading is checked against the row before it is returned: the lengths
    must agree with the card's ``planes`` for that row under one of the two
    readings the card's own schema allows — a source that counts orbits states
    the count (``029J``'s ``O`` row states 2), and a source that counts planes
    states the total (its ``Otilde+`` row states 24242) — and their number must
    be the card's own count of orbits where the card states one.  Either check
    failing raises instead of returning numbers the card does not support, and a
    row that states the total without the split raises rather than falling back
    to its citation.
    """
    digest = _digest()
    card = digest.get("plane_orbits", {}).get(tag)
    if card is None:
        raise KeyError(
            f"the digest keeps no plane rows for lattice card {tag!r}: it keeps "
            f"{sorted(digest.get('plane_orbits', {}))}"
        )
    rows = card["rows"]
    if group not in rows:
        raise KeyError(
            f"lattice card {tag} states no primitive-isotropic-plane row for {group!r}: "
            f"it states {sorted(rows)}"
        )
    if "orbit_lengths" not in rows[group]:
        raise KeyError(
            f"lattice card {tag} states the total of its {group!r} plane row but not the "
            f"lengths of the orbits it splits into: the row states {sorted(rows[group])}, "
            f"and a per-orbit length is read from the row's own `orbit_lengths` field "
            f"(dzackgarza/lattice-database card), not from its citation"
        )
    found = sorted(int(length) for length in rows[group]["orbit_lengths"])
    total = rows[group].get("planes")
    if total is not None and sum(found) != total and len(found) != total:
        raise ValueError(
            f"lattice card {tag} states per-orbit lengths {found} for {group!r}, whose sum is "
            f"{sum(found)} and whose number is {len(found)}, against the card's own planes = "
            f"{total}: a row states the number of orbits or the number of planes, and this "
            f"pair agrees with neither"
        )
    orbit_count = rows["O"]["planes"] if "O" in rows else None
    if orbit_count is not None and len(found) != orbit_count:
        raise ValueError(
            f"lattice card {tag} states {len(found)} per-orbit lengths {found} for {group!r}, "
            f"against the card's own count of {orbit_count} O-orbits of primitive isotropic planes"
        )
    return tuple(found)


# The card's own words for a split of a *line* row into orbit lengths: 029J's
# Otilde^+ citation states "the 528 lines fall in two orbits, of lengths 527 and
# 1".  As with the plane rows, the digest keeps the total as a field and the split
# in the citation, so this phrasing is what a per-orbit length is read from.
_LINE_ORBIT_LENGTH_PHRASE = re.compile(
    r"(\d+)\s+lines fall in two orbits, of lengths (\d+) and (\d+)"
)


def card_line_orbit_lengths(tag: str, group: str):
    r"""Return card ``tag``'s per-orbit numbers for the primitive isotropic lines under ``group``.

    The digest's structured ``lines`` row holds the *total* number of primitive
    isotropic lines of a row (:func:`card_line_orbit_row`); the split of that total
    into the lengths of the individual orbits is stated in the row's own citation,
    which the digest keeps verbatim.  This function reads the split there and
    returns it sorted.

    The reading is checked against the row before it is returned: the lengths must
    add up to the card's total for that row, and their number must be the card's own
    count of orbits -- the ``O`` row states that count, because ``029J``'s
    ``Otilde+`` sentence says "under O^+_10(F_2) the 528 lines fall in two orbits",
    and those two orbits are the card's two ``O``-orbits of primitive isotropic
    lines.  Either check failing raises instead of returning numbers the card does
    not support.
    """
    digest = _digest()
    card = digest.get("plane_orbits", {}).get(tag)
    if card is None:
        raise KeyError(
            f"the digest keeps no line rows for lattice card {tag!r}: it keeps "
            f"{sorted(digest.get('plane_orbits', {}))}"
        )
    rows = card["rows"]
    if group not in rows:
        raise KeyError(
            f"lattice card {tag} states no primitive-isotropic-line row for {group!r}: "
            f"it states {sorted(rows)}"
        )
    if "lines" not in rows[group]:
        raise KeyError(
            f"lattice card {tag} states a row for {group!r} without a line count: it "
            f"states {sorted(rows[group])}"
        )
    citation = rows[group]["citation"]
    match = _LINE_ORBIT_LENGTH_PHRASE.search(citation)
    if match is None:
        raise KeyError(
            f"lattice card {tag} states the total of its {group!r} line row but not the "
            f"lengths of the orbits it splits into: the phrase "
            f"{_LINE_ORBIT_LENGTH_PHRASE.pattern!r} does not occur in its citation, which "
            f"reads {citation!r}"
        )
    stated_total = int(match.group(1))
    found = sorted(int(entry) for entry in match.groups()[1:])
    total = rows[group]["lines"]
    if stated_total != total:
        raise ValueError(
            f"lattice card {tag} states {stated_total} lines in its per-orbit sentence for "
            f"{group!r}, against its own row total {total}"
        )
    if sum(found) != total:
        raise ValueError(
            f"lattice card {tag} states per-orbit lengths {found} for {group!r}, whose sum is "
            f"{sum(found)}, against the card's own total {total}"
        )
    orbit_count = rows["O"]["lines"] if "O" in rows else None
    if orbit_count is not None and len(found) != orbit_count:
        raise ValueError(
            f"lattice card {tag} states {len(found)} per-orbit lengths {found} for {group!r}, "
            f"against the card's own count of {orbit_count} O-orbits of primitive isotropic lines"
        )
    return tuple(found)


_ARITHMETIC_GROUP_QUANTITIES = {
    "lines": "line_orbits",
    "planes": "plane_orbits",
    "flags": "flag_orbits",
}
r"""The three orbit rows an arithmetic-group card states, and the field of each."""


def card_provenance() -> dict:
    r"""Return the digest's provenance: the database, the commit, and the rows kept.

    A run's report names the commit its expected values were read at, so a reader
    can reproduce the reading rather than trust the row.
    """
    return dict(_digest()["_provenance"])


def card_arithmetic_group(tag: str) -> dict:
    r"""Return arithmetic-group card ``tag``'s kept rows.

    The card's own name, LaTeX, lattice, parent group, cardinality, three orbit rows
    and the citation each row carries.  A tag the digest carries no card for raises.
    """
    cards = _digest().get("arithmetic_groups", {})
    if tag not in cards:
        raise KeyError(
            f"the digest carries no arithmetic-group card {tag!r}: it carries "
            f"{len(cards)} cards, {sorted(cards)[:3]} ... {sorted(cards)[-1:]}"
        )
    return cards[tag]


def card_arithmetic_group_row(tag: str, quantity: str) -> int:
    r"""Return arithmetic-group card ``tag``'s number of orbits of ``quantity``.

    ``quantity`` is ``lines``, ``planes`` or ``flags``: the card's own
    ``data.line_orbits``, ``data.plane_orbits`` and ``data.flag_orbits``, which
    count the orbits of primitive isotropic lines, of primitive isotropic planes
    and of isotropic flags of the group the card is about.  The 87 numerical
    polarizations state all three; the card of
    $\widetilde O^+(T_{\mathrm{En}})$ states its line and plane rows and no flag
    row.  A row the card does not state raises here, so a caller reports the
    card's silence rather than comparing against a number of another group's, and
    a tag the digest carries no card for raises naming the tags it does carry.
    """
    if quantity not in _ARITHMETIC_GROUP_QUANTITIES:
        raise KeyError(
            f"{quantity!r} is not an orbit quantity a card states: choose from "
            f"{sorted(_ARITHMETIC_GROUP_QUANTITIES)}"
        )
    card = card_arithmetic_group(tag)
    value = card.get(_ARITHMETIC_GROUP_QUANTITIES[quantity])
    if value is None:
        raise KeyError(
            f"arithmetic-group card {tag} states no {quantity} row: its citation is "
            f"{card['citation']!r}"
        )
    return value


def card_lattice(tag: str) -> dict:
    r"""Return lattice card ``tag``'s kept rows: its invariants and its orbit rows.

    The digest keeps the card's name, its LaTeX, its aliases, its signature and its
    determinant beside ``integral.primitive_orbits``, so a caller builds the lattice
    the card describes and checks the two against each other by the invariants the
    card states.  A tag the digest keeps no lattice row for raises.
    """
    cards = _digest().get("plane_orbits", {})
    if tag not in cards:
        raise KeyError(
            f"the digest carries no lattice card {tag!r}: it carries {sorted(cards)}"
        )
    return cards[tag]


def card_polarization_lattice() -> dict:
    r"""Return card ``0128``'s own name for its lattice: its tag, its name, its LaTeX."""
    card = _digest().get("polarization_counts")
    if card is None:
        raise KeyError("the digest carries no polarization-count rows: card 0128 is absent")
    return {"tag": card["tag"], "name": card["name"]}


def card_polarization_degrees() -> tuple:
    r"""Return the degrees of card ``0128``'s Table 4 rows, as the card states them."""
    card = _digest().get("polarization_counts")
    if card is None:
        raise KeyError("the digest carries no polarization-count rows: card 0128 is absent")
    return tuple(sorted(int(degree) for degree in card["rows"]))


def card_polarization_row(degree: int) -> dict:
    r"""Return card ``0128``'s Table 4 row for degree ``degree``.

    The row is ``integral.polarization_counts.{degree}``, whose ``#h`` is the
    number of orbits of primitive vectors of that square in the card's lattice
    $U \oplus E_8(-1)$ and whose ``#Γ̄_h`` is the number of classes of polarizing
    groups occurring there, with the citation the card gives for the row.  A
    degree the card states no row for raises.
    """
    card = _digest().get("polarization_counts")
    if card is None:
        raise KeyError("the digest carries no polarization-count rows: card 0128 is absent")
    row = card["rows"].get(str(degree))
    if row is None:
        raise KeyError(
            f"card {card['tag']} states no Table 4 row for degree {degree}: it states "
            f"{sorted(int(entry) for entry in card['rows'])}"
        )
    return row


