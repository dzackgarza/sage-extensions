r"""The pinned card digest, read by tag.

The numbers the Enriques acceptance compares against are not typed into a test:
they are the rows of ``dzackgarza/lattice-database``, fetched at one database
commit into ``tests/cards/lattice-database-enriques.json`` by
``tests/cards/refresh_lattice_database_enriques.py``, which records the commit it
used and refuses a ref that is not a full SHA.  This module is the reader of that
digest, so a test can name a card by tag and not restate its number.

Nothing here decides anything about a lattice: it returns the card's own
recorded row, and the card's ``reference.citation`` names the paper, table and
printed page the row comes from.
"""

from __future__ import annotations

import json
from pathlib import Path

DIGEST = (
    Path(__file__).resolve().parents[2] / "tests" / "cards" / "lattice-database-enriques.json"
)


def _digest():
    r"""Return the parsed digest, or raise naming the file it could not read."""
    if not DIGEST.exists():
        raise FileNotFoundError(
            f"the Enriques card digest {DIGEST} is not present: it is generated by "
            f"tests/cards/refresh_lattice_database_enriques.py --ref <database commit>"
        )
    return json.loads(DIGEST.read_text())


def card_plane_orbit_row(tag: str, group: str) -> int:
    r"""Return card ``tag``'s number of primitive isotropic plane orbits under ``group``.

    The row is ``integral.primitive_orbits.{group}.planes`` of the lattice card,
    or ``data.plane_orbits`` of an arithmetic-group card; both are what the
    digest keeps.  A card that states no such row raises, rather than returning
    a number of another group's.
    """
    digest = _digest()
    lattice_rows = digest.get("plane_orbits", {})
    if tag in lattice_rows:
        rows = lattice_rows[tag]["rows"]
        source = f"lattice card {tag}"
    else:
        rows = {
            name: {"planes": card["plane_orbits"]}
            for name, card in digest.get("arithmetic_groups", {}).items()
            if card.get("tag") == tag
        }
        source = f"arithmetic-group card {tag}"
    if group not in rows:
        raise KeyError(
            f"{source} states no primitive-isotropic-plane row for {group!r}: "
            f"it states {sorted(rows)}"
        )
    return rows[group]["planes"]


__all__ = ["card_plane_orbit_row", "DIGEST"]
